/*
 * Замок решения: Коллекторы остаются опасностью 3.
 *
 * ПОВОД. На Коллекторах (z = −26) замерено 0 носителей химзащиты из 1354, при
 * том что этаж несёт больше всего авторских опасных участков в игре (11
 * регистраций `registerCellHazardSite` в 10 модулях против 4 у Гармонической
 * бани и 3 у Яслей). Напрашивался вывод «опасность занижена для этажа
 * кислотных труб». Замер его не подтвердил, и правки не было.
 *
 * ЧТО ЗАМЕРЕНО (seed 1337, `scripts/floor_content_compare.ts` +
 * `scripts/hazard_bench.ts`, 4 чередующиеся пары, медиана):
 *
 *   этаж                z   danger  монстров  доля  смертность  среда  ОЗК
 *   Производственный  −14      4        796  .385       —         1370   62
 *   Перевалка         −16      3        910  .425       —            0    0
 *   Служебный         −18      3       1130  .493      .131          0    1
 *   Кремниевый        −22      4       1813  .654       —            0   85
 *   Шахта-атриум      −24      4       2095  .709      .313          0   37
 *   КОЛЛЕКТОРЫ        −26      3        208  .133   .133–.153      301    0
 *   Гарм. баня        −28      4       2608  .796      .486      20622   33
 *   Склад Гильберта   −30      4       2784  .831       —            0   29
 *
 * ПОЧЕМУ 3, А НЕ 4 — три числа, каждое против правки:
 *
 * 1. По смертности Коллекторы — тройка в точности. Живая смертность 13.3–15.3 %
 *    совпадает со Служебным этажом (13.1 %), второй тройкой пояса, и вдвое-втрое
 *    ниже соседей-четвёрок (31.3 % и 48.6 %). Доля монстров 0.133 — ниже пояса
 *    втрое, и держит её авторский `monsterMult: 0.1`, а не поле `danger`.
 *
 * 2. Защищать на этаже нечего. Из 11 участков урон жильцу наносят ДВА:
 *    жижевой отстойник (0.35/с BIO) и сок борщевика (1.8/с BIO). Остальные
 *    девять — замысленная геометрия замедления и залипания (прессовик с
 *    безопасной полосой, кабельная привязь, красный клей), у них нет
 *    `playerDamagePerSecond` вовсе. Пар Парителя бьёт своим модулем мимо
 *    клеточной опасности и жильцов не касается. Замерено: 0 смертей от среды
 *    за 4 × 60 с, медиана стоящих 4–5 из ~1480 акторов.
 *
 * 3. Химзащита следует за ЧИСЛОМ, а не за средой, и правка это не лечит.
 *    Шахта-атриум, Кремниевый колодец и Склад Гильберта несут НОЛЬ опасных
 *    клеток и при этом одевают 37, 85 и 29 человек в ОЗК и ТОК-200. Подняв
 *    Коллекторы до четвёрки, мы добавили бы четвёртый этаж, одетый по числу, а
 *    не по опасности, — и не сделали бы снаряжение осмысленным.
 *
 * ЗАПИСАННОЕ РЕШЕНИЕ. Коллекторы — людный, бедный и тихий техярус, чьи опасности
 * калечат и держат, а не разъедают. Рабочие там без защиты, и это их
 * характеристика, а не дыра.
 *
 * Отдельно: отсутствие химзащиты — свойство ВСЕХ 17 этажей опасности 3, а не
 * Коллекторов (Перевалка 0, Служебный 1). Понадобится химзащита на тройке —
 * менять надо лестницу потолка, а не опасность одного этажа.
 */
import { test } from 'node:test';
import * as assert from 'node:assert/strict';

import { Faction } from '../src/core/types';
import { DESIGN_FLOOR_ROUTES } from '../src/data/design_floors';
import { proceduralLootValueCap } from '../src/data/economics';
import { ALIFE_MAX_LEVEL } from '../src/data/alife_generation';
import { calculateMaxLootValue } from '../src/systems/procedural_loot';
import { ITEMS } from '../src/data/items';

const maintenance = DESIGN_FLOOR_ROUTES.find(r => r.id === 'maintenance');

test('Коллекторы объявлены опасностью 3 — решение по замеру, не умолчание', () => {
  assert.ok(maintenance, 'маршрут Коллекторов пропал');
  assert.equal(maintenance.z, -26);
  assert.equal(maintenance.danger, 3, 'см. шапку файла: смертность этажа совпадает со Служебным, а не с соседями-четвёрками');
});

test('поднять опасность Коллекторов ради лута нечем: полосу держит глубина', () => {
  // Полоса лута на z = −26 — это E2 по ГЛУБИНЕ (|z| ≥ 12), и опасность её не
  // двигает: строка опасности 3 даёт ровно тот же потолок, что и 4. Замок стоит
  // затем, что довод «опасность 3 → полоса лута 4 000» звучит правдоподобно и
  // ложен: на 4 000 сидит весь пояс от −14 до −24, включая все четвёрки.
  const z = maintenance!.z;
  assert.equal(proceduralLootValueCap(3, z), proceduralLootValueCap(4, z));
  for (const neighbour of ['production_belt', 'service_floor', 'shahta_atrium']) {
    const route = DESIGN_FLOOR_ROUTES.find(r => r.id === neighbour)!;
    assert.equal(
      proceduralLootValueCap(route.danger, route.z),
      proceduralLootValueCap(maintenance!.danger, z),
      `${neighbour} (опасность ${route.danger}) разошёлся с Коллекторами по полосе лута`,
    );
  }
});

test('химзащита недостижима на ЛЮБОЙ тройке — это свойство лестницы, а не этажа', () => {
  // Если однажды понадобится одеть работников тройки, чинить надо здесь, а не
  // подменой опасности одного этажа: замок сработает и подскажет место.
  const ozk = ITEMS['armor_ozk'].value;
  for (const faction of [Faction.CITIZEN, Faction.LIQUIDATOR, Faction.SCIENTIST]) {
    const best = calculateMaxLootValue(ALIFE_MAX_LEVEL, 3, faction);
    assert.ok(best < ozk, `на опасности 3 фракция ${faction} дотягивается до ОЗК (${best} ₽ против ${ozk} ₽)`);
  }
  // ...и достижима на четвёрке — иначе замок проверяет не тот случай.
  assert.ok(calculateMaxLootValue(ALIFE_MAX_LEVEL, 4, Faction.CITIZEN) > ozk);
});
