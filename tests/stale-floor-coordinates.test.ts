/* Класс дефекта, который проверка инвариантов не ловит по построению: она ищет
 * мёртвые координаты отменённой шкалы (60/100/140/180/200) только в контексте
 * имени `z`, а числа доезжают до сравнений под ДРУГИМИ именами — `nextFloor`,
 * `toFloor`, второй аргумент `ensureFloorInstanceState`. Такое сравнение молчит:
 * оно просто никогда не истинно, и авторская ветка умирает без следа.
 *
 * Найдено 2026-08-24 в точке входа: облёт камеры на жилом, в Аду и в Пустоте
 * (`nextFloor === 100 | 180 | 200`), адрес возврата из Пустоты и якорь
 * инстансов после возврата. Замок держит саму границу: маршрутный z не может
 * попасть в старую шкалу, значит любое такое сравнение мертво по построению. */

import assert from 'node:assert/strict';
import { test } from 'node:test';

import { DESIGN_FLOOR_ROUTES } from '../src/data/design_floors';
import { FLOOR_RUN_MAX_Z, FLOOR_RUN_MIN_Z, PROCEDURAL_FLOOR_ZS } from '../src/data/procedural_floors';

const BURNT_SCALE = [60, 100, 140, 180, 200];

test('ни один маршрутный этаж не живёт в отменённой шкале координат', () => {
  for (const route of DESIGN_FLOOR_ROUTES) {
    assert.ok(!BURNT_SCALE.includes(route.z), `дизайн-этаж ${route.id} вернулся на z=${route.z}`);
    assert.ok(route.z >= FLOOR_RUN_MIN_Z && route.z <= FLOOR_RUN_MAX_Z,
      `дизайн-этаж ${route.id} вне маршрутного диапазона: z=${route.z}`);
  }
  for (const z of PROCEDURAL_FLOOR_ZS) {
    assert.ok(!BURNT_SCALE.includes(z), `процедурный этаж вернулся на z=${z}`);
  }
});

test('маршрутный диапазон не достаёт до старой шкалы: сравнение с ней мертво', () => {
  // Именно это делало три ветки в `switchFloor` неисполнимыми. Пока граница
  // ниже любого из старых ключей, такое сравнение — всегда ложь.
  assert.ok(FLOOR_RUN_MAX_Z < Math.min(...BURNT_SCALE),
    'верх маршрута дорос до старой шкалы: сравнения с 60/100/140/180/200 снова стали достижимы, ' +
    'и молчаливо неверными — они означают ДРУГИЕ этажи');
});

