import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

/**
 * Глубина меша обязана совпадать с глубиной рейкастера, и эта связь держится
 * на двух числах в двух разных файлах, которые ниоткуда не видно вместе.
 *
 * Рейкастер пишет `gl_FragDepth = 1 - 0.1/dist` прямо в оконных координатах.
 * Меш идёт обычным конвейером: `gl_Position.z = ty - K` даёт NDC `1 - K/ty`, а
 * окно получает `(NDC+1)/2 = 1 - (K/2)/ty`. Значит K обязано быть РОВНО вдвое
 * больше константы рейкастера — двойка компенсирует деление, а не даёт запас.
 *
 * Цена ошибки измерена: K = 0.125 вместо 0.2 увело меш дальше поверхности, на
 * которой он стоит, весь мешевый слой проиграл depth-тест полу, стенам и
 * потолку и пропал из игры целиком — при нормально работающем рейкастере и
 * зелёных гейтах. Ни типизация, ни smoke, ни проверка компиляции шейдеров этого
 * не видят: обе программы собираются, просто одна рисует не туда.
 */

const MESH_SHADERS = readFileSync(new URL('../src/render/mesh/shaders.ts', import.meta.url), 'utf8');
const RAYCASTER = readFileSync(new URL('../src/render/webgl.ts', import.meta.url), 'utf8');

function meshDepthConstant(): number {
  const match = MESH_SHADERS.match(/gl_Position\s*=\s*vec4\(\s*tx\s*,\s*clipY\s*,\s*ty\s*-\s*([0-9.]+)\s*,\s*ty\s*\)/);
  assert.ok(match, 'не найдено gl_Position меша — изменилась форма записи, проверьте связь глубин вручную');
  return Number(match[1]);
}

function raycasterDepthConstant(): number {
  const match = RAYCASTER.match(/gl_FragDepth\s*=\s*clamp\(\s*1\.0\s*-\s*([0-9.]+)\s*\/\s*max\(\s*0\.001\s*,\s*pixelDepth/);
  assert.ok(match, 'не найдена запись глубины стен рейкастера — проверьте связь глубин вручную');
  return Number(match[1]);
}

test('глубина меша совпадает с глубиной рейкастера с точностью до деления NDC пополам', () => {
  const mesh = meshDepthConstant();
  const raycaster = raycasterDepthConstant();
  assert.ok(mesh > 0, 'константа глубины меша должна быть положительной');
  assert.ok(raycaster > 0, 'константа глубины рейкастера должна быть положительной');
  assert.equal(
    mesh,
    raycaster * 2,
    `меш пишет окну 1 - ${mesh / 2}/ty, рейкастер 1 - ${raycaster}/dist. `
    + 'Меш уедет за поверхность, на которой стоит, и мешевый слой пропадёт из кадра. '
    + 'Если константа рейкастера менялась осознанно — меняйте обе, множитель ровно 2.',
  );
});

test('пол и потолок рейкастера смещены к камере, а не от неё', () => {
  // Пол и потолок пишут себе -0.0004. Знак важен: смещение ОТ камеры отдало бы
  // им победу над мешем, стоящим на них, и вернуло бы тот же симптом другим
  // путём. Меш этот зазор перекрывает тем, что меряет перпендикулярную
  // дистанцию, а пол — радиальную, которая на том же пикселе всегда больше.
  const floorBias = RAYCASTER.match(/gl_FragDepth\s*=\s*clamp\([^;]*\)\s*-\s*0\.0004\s*;/g);
  assert.ok(floorBias && floorBias.length >= 2, 'пропало смещение глубины пола/потолка — проверьте, не перекрыли ли они меш');
});
