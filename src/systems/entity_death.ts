import type { Entity } from '../core/types';

/**
 * Единственный путь смерти сущности.
 *
 * До этого `alive = false` присваивали в шестидесяти трёх местах, и узнать о
 * смерти было неоткуда — приходилось её ИСКАТЬ. Индекс сущностей платил за это
 * полным обходом статики каждый кадр: на жилом этаже 9795 сущностей, из них с
 * `ai` всего 227, и остальные девять с половиной тысяч предметов и билбордов
 * перебирались шестьдесят раз в секунду ради события, которое случается раз в
 * несколько секунд. Замерено: 402 мкс на кадр, 2.4% кадра.
 *
 * Это ровно та же болезнь, что была у створок: смена состояния известна тому,
 * кто её делает, но не тому, кому она нужна. Лечится так же — одним путём и
 * счётчиком (`setDoorState` и `world.doorVersion`).
 *
 * Правило держится механически: `npm run check:invariants` считает сырые
 * присваивания `alive = false` вне этого файла, и число только вниз. Пропущенное
 * место не падает и не шумит — подобранный предмет просто остаётся в бакете
 * навсегда, и найти это можно лишь наткнувшись на призрак в игре.
 *
 * Возвращает `false`, если сущность уже мертва: повторная смерть эпоху не
 * двигает и лишнего обхода не заказывает.
 */
let deathEpoch = 0;

export function killEntity(e: Entity | undefined): boolean {
  if (!e || !e.alive) return false;
  e.alive = false;
  deathEpoch = (deathEpoch + 1) | 0;
  return true;
}

/** Сколько смертей видел этот забег. Читателю важно не значение, а СМЕНА:
 *  совпало с запомненным — искать некого. */
export function entityDeathEpoch(): number {
  return deathEpoch;
}
