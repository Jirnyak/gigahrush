/* ── Приказ «иди в точку» — один исполнитель на человека и тварь ── */

import { AIGoal, type Entity } from '../../core/types';
import type { World } from '../../core/world';
import { followPath, tryAssignPathToCell } from './pathfinding';

/**
 * Приказ «иди в точку»: `AIGoal.GOTO` + `ai.tx/ty`.
 *
 * Это ЕДИНСТВЕННЫЙ канал, которым один актор посылается в место снаружи его
 * собственной воли, и им пользуются восемь систем: такты сцены `moveTo` и
 * `walkOut` (`cinematics.ts`, через `aimAtSpot`), возврат актёра на пост по
 * поводку, сбор каравана, созыв по тревожной панели, шествие фракции, приход
 * мигранта A-Life, доставка гостя (`scripted_arrivals`) и разборка соседей.
 *
 * Исполнителя у приказа не было вовсе. Утилити-намерение перебирается по
 * своему такту, `enterUtilityIntent` переписывает `goal` тем, что следует из
 * намерения, и обнуляет маршрут, — а маршрута к `tx/ty` никто и не строил.
 * Замерено на жилом этаже (сид 20881, `tmp/goto_probe.ts`): из двенадцати
 * получивших приказ через СЕКУНДУ его держали НОЛЬ, к двадцать первой секунде
 * заказанная точка была затёрта у всех двенадцати, и за тридцать секунд люди
 * прошли по 33 клетки, оказавшись в среднем на 4 клетки ДАЛЬШЕ от цели, чем
 * стояли вначале. «Актёр уходит своими ногами» не работал никогда.
 *
 * Оживление, а не снос: на приказ рассчитывает живой код восьми систем и пять
 * тестов, а канал выражает то, чего утилити выразить не может и не должно —
 * волю СНАРУЖИ актора. Снести пришлось бы вместе со сценами.
 *
 * Закон ОДИН на человека и тварь, и исполнитель поэтому лежит здесь, а не в
 * `npc_fsm.ts`: видовой развилки у приказа нет и быть не может. Разница только
 * в том, ГДЕ у породы кончается бой. У человека `updateNPC` зовут уже после
 * отказа `tryFactionCombat` и `tryFleeFromMonster`; у твари бой живёт ВНУТРИ
 * `updateMonster`, поэтому приказ читается там же — сразу после того, как цель
 * не нашлась. Поднять его выше `updateMonster` нельзя: тварь под приказом
 * перестала бы отвечать на удар.
 *
 * Приказ — поверх рутины, но НЕ поверх боя и страха. Актёр сцены поэтому
 * по-прежнему отвечает на удар, а не марширует под ножом. Замерено на
 * коллекторах (`tmp/goto_holes_probe.ts`): 6 из 6 тварей под приказом, которых
 * бьют, отвечают боем.
 *
 * Приказ ПЕРЕЖИВАЕТ БОЙ, и ради этого у него своя запись (`ai.orderX/orderY`),
 * а не `ai.goal`. Пока приказ жил в курсе, первая же драка стирала его насмерть:
 * бой пишет в `goal` свой `HUNT`, и сцена или караван молча теряли актора
 * навсегда. Замерено синтетикой с одним отличием (`tmp/order_combat_probe.ts`):
 * человек и тварь, получившие приказ и подравшиеся по дороге, доходили до
 * заказанной клетки 0 раз из 1 — курс терялся на первом же кадре боя и не
 * возвращался никогда. Теперь бой кончился — приказ возобновляется тем же
 * исполнителем, с чистого маршрута.
 *
 * Почему не микроцелью. `trySetMicroGoal` по построению ОТКАЗЫВАЕТ при живой
 * боевой цели, а сами микроцели транзиентны и гаснут по таймеру. Приказ,
 * положенный туда, воспроизвёл бы ровно тот баг, который здесь чинится: не
 * поставился бы во время драки и истёк бы сам собой после неё.
 *
 * Приказ КОНЕЧЕН, и это главное его свойство: пришёл в клетку цели — гаснет
 * вместе с записью, и актор тем же кадром возвращается к своим делам. Иначе
 * один караван или одна сцена вынимали бы его из симуляции навсегда. «Пришёл»
 * меряется той же клеткой, что и у самого шага (`followPath`), — второго
 * порога достижения в проекте заводить нельзя. Срока годности у приказа НЕТ:
 * гасят его приход, отсутствие дороги и явная отмена (`clearActorOrder`), и
 * ничто иное.
 *
 * Дороги нет — приказ тоже гаснет, ровно как у `scripted_arrivals` и шествия:
 * недостижимая точка не вправе держать актора столбом до конца этажа.
 *
 * `speedMult` — не ручка приказа, а способ отдать шаг под закон самой породы:
 * тварь передаёт сюда свой `monsterMoveMult` (мокрый бетон, дебрис, укрытие),
 * иначе приказ разгонял бы, скажем, чернослиза вдвое против его же ползанья.
 * Тот же приём и в `followTacticPath`.
 */
export function tickGotoOrder(world: World, e: Entity, dt: number, speedMult = 1): boolean {
  const ai = e.ai;
  if (!ai || ai.orderX === undefined || ai.orderY === undefined) return false;
  /* Возобновление. Приказ живёт в своей записи, а `goal`/`tx`/`ty` — рабочий
   * курс, который бой, страх и страховка от залипания внутри `followPath`
   * переписывают под себя. Пришли сюда — значит ни бой, ни страх такта не
   * взяли, и курс восстанавливается с чистого маршрута: чужая дорога вела к
   * врагу, а не к заказанной клетке. */
  if (ai.goal !== AIGoal.GOTO || ai.tx !== ai.orderX || ai.ty !== ai.orderY) {
    ai.goal = AIGoal.GOTO;
    ai.tx = ai.orderX;
    ai.ty = ai.orderY;
    ai.path.length = 0;
    ai.pi = 0;
    ai.stuck = 0;
    ai.timer = 0;
  }
  // Пришёл или дороги нет — приказ гаснет вместе с курсом, одной дверью
  // отмены: второго способа погасить приказ в проекте быть не должно.
  if (world.idx(Math.floor(e.x), Math.floor(e.y)) === world.idx(Math.floor(ai.tx), Math.floor(ai.ty))) {
    clearActorOrder(e);
    return false;
  }
  if (ai.pi >= ai.path.length && tryAssignPathToCell(world, e, ai.tx, ai.ty) === 'not_found') {
    clearActorOrder(e);
    return false;
  }
  if (speedMult === 1) {
    followPath(world, e, dt);
  } else {
    const baseSpeed = e.speed;
    e.speed = baseSpeed * speedMult;
    followPath(world, e, dt);
    e.speed = baseSpeed;
  }
  /* Курс подтверждается ПОСЛЕ шага и целиком, вместе с точкой: `followPath`,
   * исчерпав маршрут до недошедшей цели, уводит актора блуждать своей же
   * страховкой от залипания — переписывает и `goal`, и `tx/ty`. Без этих трёх
   * строк приказ молча превращался бы в прогулку, а всякий, кто читает `tx/ty`
   * (сцена, отладка, реплика NPC «иду туда-то»), видел бы место прогулки. */
  ai.goal = AIGoal.GOTO;
  ai.tx = ai.orderX;
  ai.ty = ai.orderY;
  return true;
}

/**
 * Отдать приказ. Явный вход в канал для нового вызывающего.
 *
 * Четырнадцать мест ставят приказ сырьём — `ai.goal = AIGoal.GOTO` плюс
 * `tx/ty`, — и переписывать их не понадобилось: сырой курс усыновляет
 * `adoptActorOrder`. Канал от этого не раздваивается, потому что запись у него
 * всё равно одна.
 */
export function setActorOrder(e: Entity, tx: number, ty: number): void {
  const ai = e.ai;
  if (!ai) return;
  ai.orderX = tx;
  ai.orderY = ty;
  ai.goal = AIGoal.GOTO;
  ai.tx = tx;
  ai.ty = ty;
  ai.path.length = 0;
  ai.pi = 0;
  ai.stuck = 0;
  ai.timer = 0;
}

/**
 * Отменить приказ. Единственный способ погасить его снаружи — у приказа нет
 * срока годности, и «само рассосётся» не случится.
 *
 * Вместе с записью снимается и РАБОЧИЙ КУРС, если он ещё курс приказа: иначе
 * усыновление подберёт оставшийся `GOTO` следующим же кадром и заведёт приказ
 * заново, а отмена окажется невыполнимой. Чужой курс — бой, страх, рутину —
 * отмена не трогает: распоряжаться им она не вправе.
 */
export function clearActorOrder(e: Entity): void {
  const ai = e.ai;
  if (!ai) return;
  ai.orderX = undefined;
  ai.orderY = undefined;
  if (ai.goal !== AIGoal.GOTO) return;
  ai.goal = AIGoal.IDLE;
  ai.path.length = 0;
  ai.pi = 0;
  ai.timer = 0;
}

/**
 * На акторе стоит приказ.
 *
 * Сырой `GOTO` без записи считается приказом наравне с записью: усыновление
 * идёт один раз за кадр в цикле AI, и до него актор уже проходит через границы
 * захвата (`tryActorCore`, `runActorTactic`), а прямые вызовы этих функций
 * мимо цикла живут в тестах.
 */
export function actorUnderOrder(e: Entity): boolean {
  const ai = e.ai;
  return ai !== undefined && (ai.orderX !== undefined || ai.goal === AIGoal.GOTO);
}

/**
 * Усыновление сырого приказа — ОДНО место на весь проект.
 *
 * Замечает `goal === GOTO` БЕЗ своей записи и заводит её из `tx/ty`.
 *
 * Строго «без записи», а не «вслед за курсом»: `tx/ty` — рабочая точка, и в неё
 * пишет не только внешняя воля. Жижевик, шарахнувшись от обидчика, заказывает
 * себе бегство и оставляет `goal` нетронутым — то есть `GOTO` с прошлого шага
 * приказа. Замерено (`tmp/order_combat_probe.ts`): усыновление «вслед за
 * курсом» принимало это бегство за новый приказ и уводило тварь от заказанной
 * клетки, а сам испуг при этом ломался — тварь топталась в шаге от обидчика
 * вместо прежних трёх с лишним клеток отхода.
 *
 * Цена решения: пока приказ СТОИТ, сырое перенацеливание того же актора
 * пропускается — до прихода или отмены он идёт по первому адресу. Кому нужно
 * перенацелить занятого, зовёт `setActorOrder`.
 */
export function adoptActorOrder(e: Entity): void {
  const ai = e.ai;
  if (!ai || ai.goal !== AIGoal.GOTO || ai.orderX !== undefined) return;
  ai.orderX = ai.tx;
  ai.orderY = ai.ty;
}
