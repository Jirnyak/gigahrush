/* ── Приказ «иди в точку» — один исполнитель на человека и тварь ── */

import { AIGoal, type Entity } from '../../core/types';
import type { World } from '../../core/world';
import { followPath, tryAssignPathToCell } from './pathfinding';

/**
 * Приказ «иди в точку»: `AIGoal.GOTO` + `ai.tx/ty`.
 *
 * Это ЕДИНСТВЕННЫЙ канал, которым один актор посылается в место снаружи его
 * собственной воли, и им пользуются восемь систем: такты сцены `moveTo` и
 * `walkOut` (`cinematics.ts`, через `aimAtSpot`), возврат актёра на пост по
 * поводку, сбор каравана, созыв по тревожной панели, шествие фракции, приход
 * мигранта A-Life, доставка гостя (`scripted_arrivals`) и разборка соседей.
 *
 * Исполнителя у приказа не было вовсе. Утилити-намерение перебирается по
 * своему такту, `enterUtilityIntent` переписывает `goal` тем, что следует из
 * намерения, и обнуляет маршрут, — а маршрута к `tx/ty` никто и не строил.
 * Замерено на жилом этаже (сид 20881, `tmp/goto_probe.ts`): из двенадцати
 * получивших приказ через СЕКУНДУ его держали НОЛЬ, к двадцать первой секунде
 * заказанная точка была затёрта у всех двенадцати, и за тридцать секунд люди
 * прошли по 33 клетки, оказавшись в среднем на 4 клетки ДАЛЬШЕ от цели, чем
 * стояли вначале. «Актёр уходит своими ногами» не работал никогда.
 *
 * Оживление, а не снос: на приказ рассчитывает живой код восьми систем и пять
 * тестов, а канал выражает то, чего утилити выразить не может и не должно —
 * волю СНАРУЖИ актора. Снести пришлось бы вместе со сценами.
 *
 * Закон ОДИН на человека и тварь, и исполнитель поэтому лежит здесь, а не в
 * `npc_fsm.ts`: видовой развилки у приказа нет и быть не может. Разница только
 * в том, ГДЕ у породы кончается бой. У человека `updateNPC` зовут уже после
 * отказа `tryFactionCombat` и `tryFleeFromMonster`; у твари бой живёт ВНУТРИ
 * `updateMonster`, поэтому приказ читается там же — сразу после того, как цель
 * не нашлась. Поднять его выше `updateMonster` нельзя: тварь под приказом
 * перестала бы отвечать на удар.
 *
 * Приказ — поверх рутины, но НЕ поверх боя и страха. Актёр сцены поэтому
 * по-прежнему отвечает на удар, а не марширует под ножом. Замерено на
 * коллекторах (`tmp/goto_holes_probe.ts`): 6 из 6 тварей под приказом, которых
 * бьют, отвечают боем.
 *
 * Приказ КОНЕЧЕН, и это главное его свойство: пришёл в клетку цели — гаснет в
 * `IDLE`, и актор тем же кадром возвращается к своим делам. Иначе один
 * караван или одна сцена вынимали бы его из симуляции навсегда. «Пришёл»
 * меряется той же клеткой, что и у самого шага (`followPath`), — второго
 * порога достижения в проекте заводить нельзя.
 *
 * Дороги нет — приказ тоже гаснет, ровно как у `scripted_arrivals` и шествия:
 * недостижимая точка не вправе держать актора столбом до конца этажа.
 *
 * `speedMult` — не ручка приказа, а способ отдать шаг под закон самой породы:
 * тварь передаёт сюда свой `monsterMoveMult` (мокрый бетон, дебрис, укрытие),
 * иначе приказ разгонял бы, скажем, чернослиза вдвое против его же ползанья.
 * Тот же приём и в `followTacticPath`.
 */
export function tickGotoOrder(world: World, e: Entity, dt: number, speedMult = 1): boolean {
  const ai = e.ai!;
  if (ai.goal !== AIGoal.GOTO) return false;
  if (world.idx(Math.floor(e.x), Math.floor(e.y)) === world.idx(Math.floor(ai.tx), Math.floor(ai.ty))) {
    ai.goal = AIGoal.IDLE;
    ai.path.length = 0;
    ai.pi = 0;
    ai.timer = 0;
    return false;
  }
  if (ai.pi >= ai.path.length && tryAssignPathToCell(world, e, ai.tx, ai.ty) === 'not_found') {
    ai.goal = AIGoal.IDLE;
    ai.timer = 0;
    return false;
  }
  /* Курс подтверждается после шага: `followPath`, исчерпав маршрут до
   * недошедшей цели, уводит актора блуждать своей же страховкой от залипания,
   * и приказ иначе молча превращался бы в прогулку. */
  if (speedMult === 1) {
    followPath(world, e, dt);
  } else {
    const baseSpeed = e.speed;
    e.speed = baseSpeed * speedMult;
    followPath(world, e, dt);
    e.speed = baseSpeed;
  }
  ai.goal = AIGoal.GOTO;
  return true;
}
