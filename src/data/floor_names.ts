/* ── Имя этажа ────────────────────────────────────────────────────
 * Раньше здесь жили словари имён и цветов по тегу темы: шесть строк на 51 этаж,
 * из-за чего крыша подписывалась «Министерство». Имя у этажа своё, в маршрутной
 * таблице; тут остался только доступ к нему по координате.
 */

import { designFloorAtZ } from './design_floors';

/** Имя этажа по маршрутной координате. */
export function floorDisplayNameForZ(z: number): string {
  return designFloorAtZ(z)?.displayName ?? `этаж ${z}`;
}

