/* ── Матрица брони: вид защиты × тип урона → множитель ────────── */

import { ArmorType, DamageType } from '../core/types';

/**
 * Строка брони: множитель урона по каждому из шести типов.
 *
 * `1` — броня этому типу не мешает; меньше единицы — держит; больше единицы —
 * этот тип бьёт по ней ЛУЧШЕ обычного (живая сеть Червия проводит энергию).
 */
export type ArmorRow = Readonly<Record<DamageType, number>>;

/**
 * Ортогональная оси типов ось «чем ударили».
 *
 * Она НЕ сводится к типу урона: кувалда кинетическая, но плиту срывает, а
 * панические пули — нет. Различает её сегодня одна броня — бронеплиты, и только
 * у них строка расщепляется. `final` — состояние «сорвана последняя плита»,
 * а не сила удара; тем же ключом оно живёт по соседству, потому что выбирают
 * его в одной точке.
 */
export type ArmorImpact = 'weak' | 'heavy' | 'tool' | 'final';

/**
 * Профиль брони: строка по типам плюс необязательные строки по оси удара.
 *
 * Отсутствующая запись `byImpact` означает «этой броне всё равно, чем ударили»,
 * и это ЗАМЫСЕЛ, а не пробел: бетон Панельника держит нож и гранату одинаково.
 */
export interface ArmorProfile {
  readonly row: ArmorRow;
  readonly byImpact?: Readonly<Partial<Record<ArmorImpact, ArmorRow>>>;
}

/** Одинаковый множитель на все шесть типов. */
function flat(mult: number): ArmorRow {
  return {
    [DamageType.KINETIC]: mult,
    [DamageType.BUCKSHOT]: mult,
    [DamageType.ENERGY]: mult,
    [DamageType.FIRE]: mult,
    [DamageType.PSI]: mult,
    [DamageType.BIO]: mult,
  };
}

/** Плоская строка с явными исключениями по типам. */
function row(base: number, overrides: Partial<Record<DamageType, number>>): ArmorRow {
  return { ...flat(base), ...overrides };
}

/**
 * Та же строка, но брони осталось только `keep` от её защиты.
 *
 * Ось удара НЕ множит строку — она её ослабляет: «сколько защиты уцелело».
 * Прежние числа бронеплиты (0.28 → 0.68 → 0.92) ровно этим и оказались: разрыв
 * до единицы 0.72 сжимается в 0.32 и в 0.08, то есть в 4/9 и в 1/9. Поэтому
 * новых ручек здесь нет — обе доли ВЫВЕДЕНЫ из старой тройки, а не подобраны, и
 * колонка `weak` остаётся её же исходной.
 *
 * Формула работает и на уязвимости: строка больше единицы точно так же
 * стягивается к единице, а не разгоняется за неё.
 */
function weakened(base: ArmorRow, keep: number): ArmorRow {
  const out = {} as Record<DamageType, number>;
  for (const key of Object.keys(base) as unknown as DamageType[]) {
    out[key] = 1 - (1 - base[key]) * keep;
  }
  return out;
}

/** Что осталось от плиты после срывающего удара и после последней плиты. */
const PLATE_KEEP_STRIPPED = 4 / 9;
const PLATE_KEEP_FINAL = 1 / 9;

/**
 * Бронеплита: сталь.
 *
 * Держит ВЕЩЕСТВО, летящее быстро и в точку, — и почти ничего больше. Дробь по
 * стали не делает ничего (0.22), пуля пробивает её с трудом (0.28, прежнее
 * число), а вот луч прожигает сталь легче, чем пуля протыкает (0.52), жар идёт
 * сквозь металл прямо в тело (0.62) и кислота со спорами просто течёт в стыки
 * (0.86). ПСИ пластина не мешает вовсе — общий закон материала, см. ниже.
 */
const PLATE_ROW = row(0.28, {
  [DamageType.BUCKSHOT]: 0.22,
  [DamageType.ENERGY]: 0.52,
  [DamageType.FIRE]: 0.62,
  [DamageType.PSI]: 1,
  [DamageType.BIO]: 0.86,
});

/**
 * Матрица брони.
 *
 * ЗАКОН ЗАПОЛНЕНИЯ, общий на всю таблицу: колонка `KINETIC` в каждой строке
 * оставлена ровно такой, какой была до наполнения. Кинетика — то, чем в игре
 * бьют почти всегда, и старые плоские числа настраивались против неё; сдвинуть
 * их значило бы менять уровень защиты под видом избирательности. Остальные пять
 * колонок разведены вокруг кинетики по физике самого материала.
 *
 * ЗАКОН ПСИ: материальная броня не мешает ПСИ (`PSI = 1` у бетона, мокрой шкуры
 * и пластины). Это прямое следствие того, что пси-дефазинг проводит СКВОЗЬ
 * стены: если разум проходит сквозь несущую панель, он тем более проходит
 * сквозь то, что от неё откололи. Исключений два, и оба не материал: живая сеть
 * Червия — распределённый разум, и ряса культиста, пропитанная специально
 * (её резист живёт в процентах предмета, см. ниже).
 *
 * Носимая броня (`CLOTH`, `PLATE` на предмете) в бою матрицу НЕ читает: её
 * проценты живут в `ItemDef.resistances` и вычитаются из ста в `calculateDamage`.
 * Проценты И ЕСТЬ её строка — второго слоя закона поверх них не нужно, он бы
 * просто считал резист дважды. Здесь у носимого нейтральная строка ровно
 * поэтому. `armorType` предмет всё равно объявляет: по нему работает ось удара и
 * по нему предмет узнают правила материала, у которых процентов нет.
 */
export const ARMOR_MATRIX: Readonly<Record<ArmorType, ArmorProfile>> = {
  [ArmorType.NONE]: { row: flat(1) },
  [ArmorType.CLOTH]: { row: flat(1) },
  [ArmorType.PLATE]: {
    row: PLATE_ROW,
    byImpact: {
      heavy: weakened(PLATE_ROW, PLATE_KEEP_STRIPPED),
      tool: weakened(PLATE_ROW, PLATE_KEEP_STRIPPED),
      final: weakened(PLATE_ROW, PLATE_KEEP_FINAL),
    },
  },
  /**
   * Бетонная панель в руке Панельника.
   *
   * Останавливает ВЕЩЕСТВО и не мешает полю. Дробь по плите — самая её работа
   * (0.46), пуля прежняя (0.58), плеск кислоты и слизи плита принимает на себя
   * (0.62). Луч колет и плавит бетон, и скол летит в того, кто за ним (0.82);
   * пламя обтекает плиту, потому что плита не герметична (0.78).
   */
  [ArmorType.CONCRETE]: {
    row: row(0.58, {
      [DamageType.BUCKSHOT]: 0.46,
      [DamageType.ENERGY]: 0.82,
      [DamageType.FIRE]: 0.78,
      [DamageType.PSI]: 1,
      [DamageType.BIO]: 0.62,
    }),
  },
  /**
   * Мокрая шкура Лоточника, стоящего в лотке.
   *
   * Ровно противоположный бетону материал: вода гасит огонь (0.20) и смывает
   * споры с кислотой (0.48), но проводит ток — под энергией мокрая шкура ХУЖЕ
   * сухой (1.06), и это её собственный контрплей, парный к живой сети Червия.
   * Толстая мокрая плоть глушит мелкую дробь (0.52), пуля прежняя (0.58).
   */
  [ArmorType.WET_HIDE]: {
    row: row(0.58, {
      [DamageType.BUCKSHOT]: 0.52,
      [DamageType.ENERGY]: 1.06,
      [DamageType.FIRE]: 0.20,
      [DamageType.PSI]: 1,
      [DamageType.BIO]: 0.48,
    }),
  },
  /**
   * Кабельная плоть Червия без питания: не броня, а проводник.
   *
   * Базовая единица — «не защищает вовсе». Энергию проводит (1.34, прежнее
   * число), изоляция горит и тянет пламя по жиле (1.12), а гнить в кабеле
   * нечему (0.84).
   */
  [ArmorType.WIRING]: {
    row: row(1, {
      [DamageType.ENERGY]: 1.34,
      [DamageType.FIRE]: 1.12,
      [DamageType.BIO]: 0.84,
    }),
  },
  /**
   * Живая сеть: Червие у экрана или аппарата.
   *
   * Энергия остаётся его единственной ЯВНОЙ уязвимостью (1.08, прежнее число) —
   * второй слабости у него быть не должно, иначе слух про экраны перестаёт
   * что-либо значить. Всё прочее сеть держит: удар по одному узлу распределённого
   * разума в нём тонет (ПСИ 0.70), а травить в сети нечего — она держит тело, а
   * не плоть (0.66).
   */
  [ArmorType.LIVE_NET]: {
    row: row(0.56, {
      [DamageType.BUCKSHOT]: 0.50,
      [DamageType.ENERGY]: 1.08,
      [DamageType.FIRE]: 0.74,
      [DamageType.PSI]: 0.70,
      [DamageType.BIO]: 0.66,
    }),
  },
};

/**
 * Множитель брони по типу урона и, если броня её различает, по оси удара.
 *
 * Нетипизированный удар считается кинетикой — тем же правилом, что и резист
 * носимой брони в `calculateDamage`: иначе броня молча перестаёт работать.
 */
export function armorMultiplier(armor: ArmorType, damageType?: DamageType, impact?: ArmorImpact): number {
  const profile = ARMOR_MATRIX[armor];
  const line = (impact !== undefined ? profile.byImpact?.[impact] : undefined) ?? profile.row;
  return line[damageType ?? DamageType.KINETIC];
}
