/* ── Точка сборки контента ───────────────────────────────────────
 *
 * Контент в этом проекте регистрируется побочным эффектом импорта: генераторы
 * этажей на верхнем уровне объявляют пакеты NPC, сайд-квесты, зоны жилого,
 * наблюдателей событий и обработчики предметов. Пока единственной дорогой к ним
 * было ребро `systems/samosbor → gen/floor_manifest`, реестр наполнялся у того,
 * кто случайно затянул самосбор, и пустовал у того, кто не затянул: импорт
 * одного самосбора давал 464 пакета NPC, без него оставался 101. То же ребро
 * замыкало крупнейший рантайм-цикл — 293 файла.
 *
 * Теперь дорога одна и у неё есть имя. Кому нужен полный реестр — берёт его сам:
 *
 *     import './content';        // точка сборки игры
 *     import '../src/content';   // тест, которому нужен весь контент
 *
 * Это ещё не «регистрация по вызову вместо импорта»: модули по-прежнему
 * объявляют себя при загрузке, и это отдельный долг. Но решение «загрузить
 * контент» стало видимым выбором одного места, а не побочным следствием чужого
 * графа импортов.
 *
 * Слой: корневой. `ALLOWED.root` в `scripts/check-invariants.mjs` разрешает видеть
 * и systems, и gen — но разрешает это ЛЮБОМУ корневому файлу, не только этому.
 * Механической защиты от второго такого моста нет; это соглашение, а не проверка.
 *
 * Вторая точка входа — `src/test_arena.ts` (arena.html, только dev-server): она тоже
 * импортирует этот модуль, иначе у самосбора не будет генератора этажей.
 */

/* Жилой и квартиры — первыми, и это не вкусовщина. Порядок регистрации задаёт
   порядок NPC_PACKAGES и SIDE_QUESTS, а от него зависит состав плана населения
   A-Life в новом прогоне. Раньше эти два грузились раньше дизайн-этажей потому,
   что systems/samosbor тянул gen/living, а следом gen/floor_manifest тянул
   kvartiry — то есть по случайности графа. Ребро срезано, случайность ушла,
   очерёдность записана здесь явно. Проверено пробником, повторяющим список
   импортов main.ts: относительный порядок обоих реестров совпадает с
   дореформенным — все 464 общие позиции пакетов и все 421 общая позиция квестов
   идут в том же порядке. Абсолютные индексы массивов при этом сдвинуты, потому
   что девять пакетов чёрного рынка и кремниевого колодца встали в середину:
   раньше они регистрировались только при первой генерации своего этажа. */
import { regrowMaze } from './gen/living';
import './gen/kvartiry';
import { generateFloor } from './gen/floor_manifest';
import { setSamosborGenServices } from './systems/samosbor';

/* Сюжетная цепочка и тринадцать главных личностей. Сюда же приезжает
   `npc_plot_packages` — он подключается голым импортом из `data/plot`. */
import './data/plot';

/* Самосбор перестраивает этаж, но не знает, кто его порождает: слой systems
   стоит под gen и звать его не имеет права. Стройка ставится здесь. */
setSamosborGenServices({ generateFloor, regrowMaze });
