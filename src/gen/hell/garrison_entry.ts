/* ── Гарнизон входит в Ад: сцена прибытия группы Громного ──────────
 *
 * До этого момента игрок спускался в Мясной низ тайком и держал зону закрепления
 * один. Сцена показывает перелом: пять минут отстояли — и сюда вошла армия.
 *
 * Сцена НЕ заводит прибытия и не дублирует его. Группа Громного приезжает по
 * сюжету сама: шаг цепочки с `eventTags: ['hell_holdout']` закрывается, и
 * `systems/scripted_arrivals.ts` высаживает у ближайшего к зоне лифта майора с
 * охранением, публикуя `faction_event` с тем же тегом. Этот факт мира и есть
 * триггер — сцена цепляется за СОДЕРЖАНИЕ события, а не за номер шага: цепочку
 * собираются переставлять, и индексы поедут.
 *
 * Майор берётся ролью `packageId`: он уже здесь, сцена его лишь зовёт. Штурмовая
 * группа — обычные ликвидаторы, твари — вид из общего реестра, бой — обычный бой
 * по матрице отношений. Кто кого, решают стволы, а не такты: майор может и лечь.
 *
 * ЧЕРНОВИК РЕЧИ. Реплики — рабочая заглушка в тоне канона, помечена DRAFT.
 *
 * Контракт сцен — `cutscene.md`.
 */

import { Faction, MonsterKind, Occupation } from '../../core/types';
import { designNpcFloorKey } from '../../data/plot';
import { registerFloorScene } from '../../systems/cinematics';
import { HELL_ANCHOR_ZONE_ALIAS } from './plot_chain';

export const HELL_GARRISON_ENTRY_SCENE_ID = 'hell_garrison_entry' as const;
/** Тег события, которым сюжет объявляет удержание закрытым, а группу — прибывшей. */
export const HELL_GARRISON_ENTRY_EVENT_TAG = 'hell_holdout' as const;
/** Тип события прибытия. Шаг цепочки публикует свой `quest_completed` с тем же тегом. */
export const HELL_GARRISON_ENTRY_EVENT_TYPE = 'faction_event' as const;

const HELL_FLOOR_KEY = designNpcFloorKey('hell');

/* Голоса те же, что у обороны форпоста: это те же люди этажом ниже. */
const MAJOR_VOICE = '#cfe3c8';
const SQUAD_VOICE = '#e6d7a8';

/* ── Геометрия кадра ───────────────────────────────────────────────
 *
 * Якорь — «Зона закрепления», и размер её ФИКСИРОВАН таблицей сюжетных комнат:
 * 13x11 (`data/plot_rooms.ts`). Смещения считаются от центра, поэтому лежат в
 * пределах ox ±6, oy ±5, и клетка комнаты выходит как (6+ox, 5+oy).
 *
 * Занятые обстановкой клетки обходим руками: свеча (1,1), лампа (6,5) ровно в
 * центре, полка (11,1), аппарат (6,9). Центр комнаты непроходим — это норма, и
 * ставить на него человека нельзя: `packageId` переносит его туда без проверки.
 */
/** Полоса входа: южный край зала, ряд клеток 9. Аппарат в (6,9) обходим смещением. */
const ENTRY_OY = 4;
const MAJOR_OX = -3;
const VANGUARD_OX = 1;
/** Строй после команды — северная половина зала, ряд 3: выше лампы и чисто. */
const FORMATION_OY = -2;

/* ── Мягкий предел акторов: почему каст этой сцены мал ──────────────
 *
 * Ад — единственный этаж, забитый акторами ПОД САМУЮ КРЫШКУ: замерено 19 человек
 * и 4077 тварей, ровно 4096 при общем пределе 4096 (коллекторы 1769,
 * министерство 2101). Слотов на спавн там ноль, и `entitySpawnSlots` молча
 * отдаёт пустой список — без ошибки и без записи.
 *
 * Отсюда два следствия для автора, и оба намеренные:
 *   — каст держим скромным, чтобы он влезал в слоты, освободившиеся за пять
 *     минут удержания: игрок к этому моменту выбил вокруг зоны не один десяток;
 *   — голос сцены несёт МАЙОР, а он приходит ролью `packageId` и предела не
 *     касается вовсе. Даже если этаж не отдал ни одного слота, сцена остаётся
 *     сценой: командир входит, отдаёт команду, кадр её показывает.
 */
const VANGUARD_COUNT = 16;
const VANGUARD_LEVEL = 10;
/* Ровный веер, а не кучки: строй обязан читаться строем. Ровно тот случай, ради
 * которого у расстановки есть авторский `clusters`. */
const VANGUARD_CLUSTERS = 1;
const VANGUARD_SPREAD = 6;

/* Твари приходят ЗА СТВОРКАМИ и снаружи: половина диагонали зала — восемь с
 * половиной клеток, значит кольцо тринадцати кладёт их в коридорах вокруг, а не
 * в самом зале. Идти им недалеко: первое столкновение должно попасть в кадр. */
const WAVE_COUNT = 10;
const WAVE_LEVEL = 5;
const WAVE_RING = 13;
const WAVE_SPREAD = 5;
/* Дерущимся ролям нужен ЗАВЕДОМО широкий поводок: возврат за поводок гасит бойцу
 * цель, память об ударе и скан разом, и посаженная на кольце тварь пришла бы к
 * взводу слепой. Своё кольцо она обязана перекрывать с запасом. */
const WAVE_LEASH = 30;

/* Общий поводок: зал плюс подходы к нему. Держит отпущенных в бою у места
 * действия и при этом шире кольца тварей — блокировать бой он не должен.
 * Стоящих в строю он не касается: пока роль сцены на человеке, его держит
 * короткий поводок к СВОЕМУ месту. */
const SCENE_LEASH = 24;

/* Радиус облёта считаем от комнаты: половина МЕНЬШЕЙ стороны (11/2) минус
 * клетка даёт четыре с половиной. Берём два — майор к финалу стоит в двух
 * клетках от центра по своему поводку, и круг радиусом два укладывается в зал
 * целиком, а не скребёт простенок. */
const ORBIT_RADIUS = 2;
/** Поводок командира: на нём стоит кадр, общий поводок его из кадра выпускает. */
const MAJOR_LEASH = 2;

registerFloorScene({
  id: HELL_GARRISON_ENTRY_SCENE_ID,
  floorKey: HELL_FLOOR_KEY,
  anchorRoomAlias: HELL_ANCHOR_ZONE_ALIAS,
  /* Первая в игре сцена на событийном триггере. Ждём не приход на этаж — на Аду
   * игрок к этому времени уже стоит пять минут, — а сам факт высадки группы. */
  trigger: {
    kind: 'event',
    eventType: HELL_GARRISON_ENTRY_EVENT_TYPE,
    tag: HELL_GARRISON_ENTRY_EVENT_TAG,
  },
  /* Потолок с запасом: такты укладываются примерно в минуту, но упереться в него
   * нельзя — сцена оборвалась бы до столкновения, и вход армии кончился бы
   * ничем. */
  maxSeconds: 150,
  leash: SCENE_LEASH,
  actors: [
    /* Майор уже на этаже: его высадил лифт по сюжету. Сцена его зовёт, а не
     * создаёт заново, — иначе на Аду оказалось бы два Громных. */
    { role: 'major', packageId: 'major_grom', ox: MAJOR_OX, oy: ENTRY_OY, leash: MAJOR_LEASH },

    // Штурмовая группа. Пятеро охранения приехали с майором сами; в кадр входит
    // не охранение, а подразделение — это и есть перелом.
    {
      role: 'vanguard',
      count: VANGUARD_COUNT,
      faction: Faction.LIQUIDATOR,
      occupation: Occupation.HUNTER,
      level: VANGUARD_LEVEL,
      ox: VANGUARD_OX,
      oy: ENTRY_OY,
      spread: VANGUARD_SPREAD,
      clusters: VANGUARD_CLUSTERS,
    },

    // Твари ждут своего такта: сперва строй и команда, потом столкновение.
    {
      role: 'wave',
      monster: MonsterKind.TVAR,
      count: WAVE_COUNT,
      level: WAVE_LEVEL,
      ox: 0,
      oy: 0,
      ring: WAVE_RING,
      spread: WAVE_SPREAD,
      leash: WAVE_LEASH,
      deferred: true,
    },
  ],
  beats: [
    // Подлёт без `look`: кадр идёт по курсу и поворачивает вместе с дорогой.
    { kind: 'fly', to: { ox: -5, oy: -3 }, speed: 12, height: 1.0 },
    // Короткий кадр внутри зала — уже с `look`: камера берёт входящий строй.
    { kind: 'fly', to: { ox: -4, oy: 1 }, look: { role: 'vanguard' }, speed: 5, height: 0.9 },

    // DRAFT
    { kind: 'say', role: 'major', text: 'Зона закрепления. Пять минут ты отстоял. Принято.', color: MAJOR_VOICE },
    { kind: 'pause', seconds: 2 },
    { kind: 'say', role: 'major', text: 'Группа — внутрь. Первое отделение на створки, второе по периметру.', color: MAJOR_VOICE },

    /* Развод по команде: `moveTo` снимает роль сцены с названных и только с них.
     * Пока майор стоит у входа, группа проходит мимо него вглубь зала — приказ
     * читается движением, а не строкой в журнале. */
    { kind: 'moveTo', roles: ['vanguard'], to: { ox: 0, oy: FORMATION_OY }, wait: 6 },
    { kind: 'say', role: 'vanguard', text: 'Есть створки.', color: SQUAD_VOICE },

    // Кадр переходит на командира и дальше субъекта не меняет.
    { kind: 'fly', to: { ox: 1, oy: 0 }, look: { role: 'major' }, speed: 5, height: 0.85 },
    { kind: 'say', role: 'major', text: 'Дальше низ держим мы. Не поодиночке.', color: MAJOR_VOICE },

    // Столкновение: сперва твари приходят, потом их замечают. Порядок обратный
    // форпосту намеренно — здесь их видят раньше, чем слышат, зал открыт.
    { kind: 'materialize', role: 'wave' },
    { kind: 'release', roles: ['wave'] },
    { kind: 'say', role: 'vanguard', text: 'Движение за створками. Идут.', color: SQUAD_VOICE },
    { kind: 'say', role: 'major', text: 'Огонь по готовности. Патроны считаем после.', color: MAJOR_VOICE },

    /* Командира выводим на середину: круг вокруг прижатого к южной стене
     * наполовину лежит в бетоне. `moveTo` снимает с него роль — дальше его
     * держит собственный поводок, уже к якорю, то есть к центру зала. */
    { kind: 'moveTo', roles: ['major'], to: { ox: 0, oy: 1 }, wait: 3 },
    { kind: 'pause', seconds: 3 },
    { kind: 'orbit', around: { role: 'major' }, radius: ORBIT_RADIUS, speed: 0.4, height: 0.95, seconds: 6 },

    // Дальше камера уходит к игроку. Исхода не ждём: он теперь общий.
  ],
});
