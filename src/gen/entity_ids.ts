/* ── Номера сущностей ─────────────────────────────────────────────
 *
 * Один владелец на всю генерацию. До этого модуля правило «с какого номера
 * начинать» жило сорока магическими числами по генераторам этажей: тридцать
 * шесть писали `10000`, один `1000`, три выводили из числа сюжетных слотов, а
 * три — ад, квартиры и коллекторы — писали единицу и садились прямо в
 * зарезервированный диапазон. Молча: предмет с чужим номером выдавал себя за
 * сюжетную личность, доставка авторских пакетов считала человека уже
 * поставленным, а A-Life вычищала «переехавшего» — так с ада каждую загрузку
 * пропадали два Сторожа, Скрежет, Пасть и Певчий налога.
 *
 * Правило теперь написано один раз и здесь. Этаж по-прежнему заполняет себя сам
 * — своя геометрия, свои люди, свой контент; общей стала только выдача номеров
 * и проверка на выходе.
 */

import type { Entity } from '../core/types';
import { getPlotNpcCount } from '../data/npc_packages';

/**
 * Первый номер, свободный для обычной сущности.
 *
 * Диапазон `1..getPlotNpcCount()` — номера слотов сюжетных личностей: их
 * читают A-Life, сейв и предикат `isPlotNpc`. Запас в тысячу сверх него — не
 * суеверие, а место под личностей, которых допишут: список слотов растёт, а
 * сохранения игроков помнят старые числа.
 */
export function firstRuntimeEntityId(): number {
  return getPlotNpcCount() + 1000;
}

/** Свежий счётчик номеров для генерации этажа. */
export function newEntityIdCursor(): { v: number } {
  return { v: firstRuntimeEntityId() };
}

/**
 * Строгость по среде. Вне браузера (тесты, скрипты, гейт) столкновение номеров —
 * ошибка автора, и найти её должен он, а не игрок. В браузере ошибка чужая, а
 * платит за неё живой человек, поэтому там номер молча выдаётся заново.
 *
 * Тот же приём, что у именованных комнат: `assertNamedRooms` валит сборку, а
 * промах точки кадра приземляется на ближайшую проходимую клетку.
 */
const STRICT = typeof process !== 'undefined' && process.versions?.node !== undefined;

/**
 * Номер сущности обязан быть один на всю сцену. Проверка стоит одного прохода
 * по массиву и висит на границе генерации: забытый модуль со своим счётчиком
 * дальше неё не проходит.
 *
 * НЕ ПРОВЕРЯЮТСЯ неположительные номера. Это не сущности, а ЗАГОТОВКИ: `id <= 0`
 * — метка шаблона обычного жителя, по которой `isAmbientNpcCandidate`
 * (`systems/alife.ts`) узнаёт, кого материализовать из пула A-Life. Процедурные
 * этажи ставят так всё своё население, и настоящий номер такой человек получает
 * при материализации. Выдать заготовке номер здесь значит сделать её обычным
 * жителем без личности — этаж перестанет брать людей из пула и начнёт усыновлять
 * новых: замерено, 1954 новых человека за один визит вместо 1147 из пула.
 *
 * Возвращает число исправленных — ноль означает, что этаж чист.
 */
export function enforceUniqueEntityIds(entities: Entity[], label: string): number {
  const seen = new Set<number>();
  let next = 0;
  for (const entity of entities) {
    if (entity.id >= next) next = entity.id + 1;
  }
  const collisions: string[] = [];
  let fixed = 0;
  for (const entity of entities) {
    if (entity.id <= 0) continue;
    if (!seen.has(entity.id)) {
      seen.add(entity.id);
      continue;
    }
    if (collisions.length < 8) collisions.push(`${entity.id} (${entity.type}${entity.name ? ` ${entity.name}` : ''})`);
    entity.id = next++;
    seen.add(entity.id);
    fixed++;
  }
  if (fixed > 0 && STRICT) {
    throw new Error(
      `[ENTITY_IDS] ${label}: ${fixed} сущностей делят чужой номер — ${collisions.join('; ')}`
      + '\nСчётчик номеров берётся из newEntityIdCursor(), и продвижение обязано возвращаться наружу.',
    );
  }
  return fixed;
}
