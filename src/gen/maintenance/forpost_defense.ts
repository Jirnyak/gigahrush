/* ── Оборона форпоста: сцена-пролог коллекторов ────────────────────
 *
 * Первый приход на коллекторы. Форпост Майора Громного держит трубу между водой,
 * тварью и людьми за дверью — и именно этим он и занят, когда игрок появляется на
 * этаже. Взвод отбивает наплыв, отбивает успешно, майор командует держать строй —
 * и в этот момент из темноты приходит вторая волна, уже большая. Кадр уходит к
 * игроку, не дожидаясь исхода: бой продолжается без зрителя.
 *
 * Сцена не заводит ни одной системы. Твари — виды из общего реестра, взвод —
 * обычные ликвидаторы, бой — обычный бой по матрице отношений. Кто выживет, решают
 * стволы и уровни, а не такты: майор может и лечь, и тогда этаж останется без
 * командира форпоста. Это допустимый исход.
 *
 * ЧЕРНОВИК РЕЧИ. Реплики — рабочая заглушка в тоне канона, помечена DRAFT.
 * Финальные приходят от внешнего сценариста (`scenarist.md`).
 *
 * Контракт сцен — `cutscene.md`.
 */

import { Faction, MonsterKind, Occupation } from '../../core/types';
import { designNpcFloorKey } from '../../data/plot';
import { registerFloorScene } from '../../systems/cinematics';
import { FORPOST_ANCHOR } from './forpost';

export const FORPOST_DEFENSE_SCENE_ID = 'maintenance_forpost_defense' as const;
const MAINTENANCE_FLOOR_KEY = designNpcFloorKey('maintenance');

const MAJOR_VOICE = '#cfe3c8';
const SQUAD_VOICE = '#e6d7a8';

/* Форпост тесен и будет тесен: своё место ищется как сплошной блок стены, а в
 * прорытом лабиринте такого блока нет — генератор занимает готовую комнату, и
 * размер её решает этаж, а не мы. Выходит порядка тринадцати на семь.
 *
 * Это не помеха, а смысл кадра: бой у чокпоинта растекается по трубам вокруг, и
 * взвод стоит в проходах, а не строем в помещении. Но смещения точек кадра из-за
 * этого обязаны лежать внутри МАЛОЙ комнаты — не дальше пары клеток от центра.
 * Цифра, верная для зала пролога двадцать на четырнадцать, здесь ушла бы в бетон. */
const SQUAD_SPREAD = 9;
const CAMERA_INSET = 2;
/* Радиус облёта обязан помещаться в комнату С ЗАЗОРОМ, а не впритык.
 *
 * Половина высоты зала тринадцать на семь — три с половиной клетки. Круг радиусом
 * три проходит в полуклетке от стены, а камера держит от стен свой зазор в треть
 * клетки — и почти весь оборот идёт прижатой. Замерено: радиус семь давал 43%
 * кадров вплотную к простенку, радиус три — те же 43%, радиус два — норму.
 *
 * Отсюда правило: радиус не больше половины МЕНЬШЕЙ стороны минус клетка. Здесь
 * это два, и близкий кадр тесному форпосту к лицу. */
const ORBIT_RADIUS = 2;

/* Вторая волна приходит СО ВСЕХ СТОРОН и издалека — за пределом прорисовки, то
 * есть её слышно раньше, чем видно. Дойти до форпоста они успеют уже без зрителя. */
const SECOND_WAVE_RING = 70;

registerFloorScene({
  id: FORPOST_DEFENSE_SCENE_ID,
  floorKey: MAINTENANCE_FLOOR_KEY,
  anchorRoomAlias: FORPOST_ANCHOR,
  trigger: { kind: 'first_visit' },
  /* Потолок с большим запасом. Он не тюнинг темпа: `awaitDeath` держит своё
   * ожидание сам. Но упереться в потолок нельзя — сцена оборвётся ДО последних
   * тактов, и вторая волна не придёт вовсе. Так она однажды и не пришла. */
  maxSeconds: 240,
  /* Бой у форпоста — не повод разойтись по этажу. Отпущенные в живой мир люди
   * расходятся: кто добивать, кто за едой, — и облёт вокруг говорящего становится
   * облётом вокруг пустого места. Поводок держит их в комнате и подходах к ней. */
  leash: 14,
  actors: [
    /* Майор держится СЕРЕДИНЫ. На нём стоит весь кадр, а общий поводок шире самой
     * комнаты — с ним командир уходит из кадра совершенно законно, и облетать
     * оказывается некого. Короткий поводок ему драться не мешает: это возврат
     * цели, а не запрет. */
    { role: 'major', packageId: 'major_grom', ox: 0, oy: 0, leash: 2 },

    // Взвод: не строй, а горсть постов по проходам вокруг командира.
    {
      role: 'squad',
      count: 44,
      faction: Faction.LIQUIDATOR,
      occupation: Occupation.HUNTER,
      level: 11,
      ox: 0,
      oy: 1,
      spread: SQUAD_SPREAD,
    },

    // Первая волна — уже внутри периметра, потому и бой начинается сразу. Сборки:
    // быстрые и слабые, взвод их разбирает уверенно. Это разминка, а не угроза, —
    // иначе вторая волна не прочтётся как перелом.
    {
      role: 'wave1',
      monster: MonsterKind.SBORKA,
      count: 18,
      level: 2,
      ox: 0,
      oy: 0,
      ring: 6,
      spread: 5,
    },

    // Вторая волна ждёт своего такта и приходит кольцом издалека.
    {
      role: 'wave2',
      monster: MonsterKind.TVAR,
      count: 48,
      level: 4,
      ox: 0,
      oy: 0,
      ring: SECOND_WAVE_RING,
      spread: 6,
      deferred: true,
    },
  ],
  beats: [
    // Бой идёт с первого кадра: поводок снят раньше, чем камера доехала. Зритель
    // прилетает на уже начавшееся, а не на живую картину, ждущую его.
    { kind: 'release', roles: ['major', 'squad', 'wave1'] },

    // Дальний подлёт — без `look`: кадр смотрит по курсу и поворачивает вместе с
    // трубами. Скорость по длине дороги, как в прологе жилого.
    { kind: 'fly', to: { ox: -CAMERA_INSET, oy: -CAMERA_INSET }, speed: 18, height: 0.9 },
    /* Здесь кадр СТОИТ И СМОТРИТ, а не облетает.
     *
     * Бой у форпоста уходит в трубы шириной в клетку, и майор посреди него стоит
     * где придётся. Облёт вокруг человека в трубе — это скрёб по стене весь
     * оборот: круг просто некуда вписать. Держать кадр можно везде.
     *
     * Точка внимания при этом живая и переживает такт: `fly` навёл её на майора,
     * `pause` держит время, а смотрит кадр всё это время на него — даже когда он
     * отходит. Ради этого прицел и сделан свойством сцены, а не такта. */
    { kind: 'fly', to: { ox: -CAMERA_INSET, oy: CAMERA_INSET }, look: { role: 'major' }, speed: 7, height: 0.85 },
    { kind: 'pause', seconds: 8 },

    // Ждём, пока взвод добьёт первую волну. Такт не назначает исход: не успеют —
    // закроется по своему ожиданию, и майор скажет то же самое посреди боя.
    { kind: 'awaitDeath', role: 'wave1', timeout: 45 },

    /* Командиру нужна середина: облёт вокруг угла упирается в стену. Но ВЕДУТ
     * его сюда не поручением, а его же поводком в две клетки — поручение как раз
     * поводок и снимает. Пока `moveTo` висит, актёр вычеркнут из удержания у
     * якоря до конца сцены (поручение живёт, пока сцена идёт), и бой уводил
     * майора из зала: замерено восемь с половиной клеток при зале тринадцать на
     * девять, то есть за стену. Поводок делает ровно то же самое и вдобавок
     * гасит боевую цель на время возврата, поэтому здесь остаётся только время. */
    { kind: 'pause', seconds: 6 },
    { kind: 'fly', to: { ox: CAMERA_INSET, oy: -CAMERA_INSET }, look: { role: 'major' }, speed: 6, height: 0.7 },

    // DRAFT
    { kind: 'say', role: 'major', text: 'Братцы, не боимся! Держать строй, оценим обстановку.', color: MAJOR_VOICE },
    // Ось — на говорившем, а не на центре масс роли: иначе бабл уходит за край.
    { kind: 'orbit', around: { speaker: true }, radius: ORBIT_RADIUS, speed: 0.3, height: 0.8, seconds: 5 },

    // Вторая волна: сперва крик, потом твари. Порядок важен — так зритель узнаёт
    // об этом ушами, как и взвод.
    { kind: 'say', role: 'squad', text: 'О нет... ещё твари! Со всех сторон!', color: SQUAD_VOICE },
    { kind: 'materialize', role: 'wave2' },
    { kind: 'release', roles: ['wave2'] },

    // Кадр задерживается ровно настолько, чтобы зритель увидел НАЧАЛО второго
    // боя, а не только услышал о нём. Уйти сразу после крика — значит показать
    // угрозу словами и не показать делом.
    //
    // И снова через середину: к этому такту майор уже отвоевал своё и стоит где
    // придётся, а круг вокруг прижатого к стене наполовину лежит в стене — кадр
    // тогда не облетает, а скребёт по простенку. Возвращает его тот же поводок.
    { kind: 'pause', seconds: 3 },
    { kind: 'orbit', around: { role: 'major' }, radius: ORBIT_RADIUS, speed: 0.5, height: 0.95, seconds: 5 },

    // Дальше камера сама уходит к игроку. Исхода не ждём: чем он кончится, игрок
    // узнает, дойдя туда своими ногами.
  ],
});
