/* ── Разворот Заслонова: генерал переходит к культистам ────────────
 *
 * Перелом сюжета. Игрок приходит на министерство за патронами — и человек,
 * который на смотре гарнизона объявлял строю, что самосборы участились,
 * оказывается их выгодоприобретателем. Тот же генерал, тот же вестибюль, тот же
 * голос: сцена намеренно стоит на том же якоре, что и смотр, и зовёт ту же
 * личность ролью `packageId`. Нового генерала здесь не заводится.
 *
 * Сцена не назначает исхода (`cutscene.md`, главное правило). Она меняет сторону
 * и отпускает людей — дальше кто в кого стреляет, решает матрица отношений, а
 * убьёт ли игрок Заслонова, решает бой. Такта «драка» в словаре нет и не нужно:
 * враждебные фракции плюс `release` — это и есть драка.
 *
 * ⚠️ Порядок обязателен: `defect` ДО `release`. Пока роль сцены на человеке, он
 * декорация и стрелять не станет.
 *
 * ЧЕРНОВИК РЕЧИ. Реплики — рабочая заглушка в тоне канона, помечена DRAFT.
 */

import { Faction, Occupation } from '../../core/types';
import { designNpcFloorKey } from '../../data/plot';
import { registerFloorScene } from '../../systems/cinematics';
import { MINISTRY_VESTIBULE_ANCHOR } from './geometry';
import { PARADE_GENERAL_ID } from './garrison_parade';

export const MINISTRY_BETRAYAL_SCENE_ID = 'ministry_zaslonov_betrayal' as const;
/**
 * Тег, которым сюжет объявляет разворот случившимся. Сцена цепляется за
 * СОДЕРЖАНИЕ факта мира, а не за номер шага цепочки: цепочку собираются
 * переставлять, и числовые индексы поедут вместе с ней.
 */
export const ZASLONOV_BETRAYAL_EVENT_TAG = 'zaslonov_betrayal' as const;
/**
 * Тип события. Шаг цепочки — обычный квест, и его закрытие публикует
 * `quest_completed`, донося объявленные шагом `eventTags` до наблюдателей
 * (`questTags` в `systems/quests.ts`). Отдельного типа события под сюжет тут не
 * заводится и заводить нельзя.
 */
export const ZASLONOV_BETRAYAL_EVENT_TYPE = 'quest_completed' as const;

const MINISTRY_FLOOR_KEY = designNpcFloorKey('ministry');

/* Голос генерала тот же, что на смотре: это должен читаться один и тот же
 * человек. Цвет объявлен здесь заново намеренно — модули контента одного этажа
 * замкнуты на себя, и общего словаря голосов у них нет. */
const GENERAL_VOICE = '#e6ddbe';
const GUARD_VOICE = '#c9b6a0';

/* ── Геометрия кадра ───────────────────────────────────────────────
 *
 * Якорь — центральный вестибюль 33x33 (`gen/ministry/geometry.ts`), смещения
 * лежат в пределах ±16. Обстановка в зале — только лампы по двум полосам,
 * oy −13.5 и +12.5, поэтому середина зала чиста: ставить туда человека,
 * которого переносит `packageId` без проверки клетки, безопасно.
 *
 * Смотр разводит строй на запад, и после него зал пуст: сцена играется позже и
 * ей никто не мешает.
 */
/** Генерал — в середине зала: вокруг него идёт весь кадр. */
const GENERAL_OX = 0;
const GENERAL_OY = 0;
/** Телохранители кольцом вокруг него: не строй, а охранение. */
const GUARD_RING = 4;
const GUARD_SPREAD = 2;
const GUARD_COUNT = 6;
const GUARD_LEVEL = 14;

/* Радиус облёта считаем от комнаты: половина МЕНЬШЕЙ стороны (33/2) минус
 * клетка — пятнадцать с половиной. Берём пять: кольцо охранения на четырёх, и
 * кадр обязан идти СНАРУЖИ него, не сквозь спины. */
const ORBIT_RADIUS = 5;
/**
 * Поводок генерала. На нём стоит кадр от первой реплики до последней, а после
 * `defect` он ещё и рвётся в бой: без своего короткого поводка он уходит из
 * кадра совершенно законно.
 */
const GENERAL_LEASH = 3;
/**
 * Общий поводок: зал и подступы к нему. Держит уже враждебное охранение у места
 * действия последние секунды кадра и при этом заведомо шире кольца — блокировать
 * бой поводок не должен. Как только сцена закрылась, он не действует вовсе.
 */
const SCENE_LEASH = 14;

registerFloorScene({
  id: MINISTRY_BETRAYAL_SCENE_ID,
  floorKey: MINISTRY_FLOOR_KEY,
  anchorRoomAlias: MINISTRY_VESTIBULE_ANCHOR,
  /* Событийный триггер, а не первый визит: первый визит министерства занят
   * смотром гарнизона, да и разворот обязан случиться ПОСЛЕ него — иначе
   * предупреждение о самосборах некому будет вспомнить. */
  trigger: {
    kind: 'event',
    eventType: ZASLONOV_BETRAYAL_EVENT_TYPE,
    tag: ZASLONOV_BETRAYAL_EVENT_TAG,
  },
  /* Потолок с запасом на ПОДЛЁТ: игрок приезжает на случайный из шестнадцати
   * лифтов этажа, и дорога до центра бывает вчетверо длиннее прямой. Сами такты
   * укладываются примерно в полминуты. */
  maxSeconds: 150,
  leash: SCENE_LEASH,
  actors: [
    /* Генерал уже живёт на этаже — его ставит общая доставка авторских пакетов
     * по `spawnRoomAlias`. Сцена его ЗОВЁТ: создать второго значило бы, что
     * игрок убьёт двойника, а настоящий останется своим.
     *
     * Убит раньше — роль просто пуста, и сцена проходит без голоса. Это лучше
     * подставного генерала: смерть — постоянный факт, и переигрывать её сцене
     * не принадлежит. */
    { role: 'general', packageId: PARADE_GENERAL_ID, ox: GENERAL_OX, oy: GENERAL_OY, leash: GENERAL_LEASH },
    /* Телохранители. Обычные ликвидаторы до такта `defect` и обычные культисты
     * после: своего поведения у них нет, и заводить его сцене нечем. */
    {
      role: 'guards',
      count: GUARD_COUNT,
      faction: Faction.LIQUIDATOR,
      occupation: Occupation.HUNTER,
      level: GUARD_LEVEL,
      ox: GENERAL_OX,
      oy: GENERAL_OY,
      ring: GUARD_RING,
      spread: GUARD_SPREAD,
    },
  ],
  beats: [
    // Дальний подлёт: без `look` кадр смотрит по курсу и поворачивает вместе с
    // коридорами. Точка входа — восточная четверть зала.
    { kind: 'fly', to: { ox: 11, oy: 8 }, speed: 20, height: 1.1 },
    // Короткий кадр внутри зала — уже с `look`: камера берёт генерала и дальше
    // субъекта не меняет до самого конца.
    { kind: 'fly', to: { ox: 6, oy: 4 }, look: { role: 'general' }, speed: 5, height: 0.9 },
    { kind: 'orbit', around: { role: 'general' }, radius: ORBIT_RADIUS, speed: 0.22, height: 0.95, seconds: 6 },

    // DRAFT
    { kind: 'say', role: 'general', text: 'Вы за патронами. Патроны кончились. Кончились ещё до вас.', color: GENERAL_VOICE },
    { kind: 'say', role: 'guards', text: 'Вестибюль чист, товарищ генерал.', color: GUARD_VOICE },
    { kind: 'say', role: 'general', text: 'Я говорил строю, что самосборы участились. Не сказал только, по чьему расписанию.', color: GENERAL_VOICE },
    { kind: 'orbit', around: { role: 'general' }, radius: ORBIT_RADIUS, speed: -0.2, height: 1.1, seconds: 5 },
    { kind: 'say', role: 'general', text: 'Гарнизон удвоен. Партия думает — против самосборов.', color: GENERAL_VOICE },
    { kind: 'say', role: 'general', text: 'Шинели снять. Ликвидатор — это должность, а не судьба.', color: GENERAL_VOICE },

    /* Разворот. Такт меняет СТОРОНУ, и только её: ни выстрела, ни смерти он не
     * назначает. Личное отношение к игроку валится в дно — свидетеля здесь
     * оставлять не собирались.
     *
     * Принадлежность генерала переживёт этот этаж: `applyDefection` ставит на
     * личность событийный оверрайд A-Life, и анкета пакета его больше не
     * перебьёт (`systems/alife.ts`, «Принадлежность, переписанная событием»).
     * Телохранителям переживать нечего — их создала сама сцена. */
    { kind: 'defect', roles: ['general', 'guards'], faction: Faction.CULTIST, playerRelation: -100 },
    // И только теперь зал живой: до этой строки каст был декорацией.
    { kind: 'release' },

    { kind: 'say', role: 'general', text: 'Ликвидируйте свидетеля.', color: GENERAL_VOICE },
    /* Последний кадр — и камера уходит к игроку. Исхода сцена не ждёт: дальше
     * обычный бой по общим правилам, и генерал в нём смертен ровно так же, как
     * всякий другой. */
    { kind: 'orbit', around: { role: 'general' }, radius: ORBIT_RADIUS, speed: 0.35, height: 0.9, seconds: 4 },
  ],
});
