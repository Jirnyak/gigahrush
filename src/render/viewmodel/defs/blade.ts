/**
 * Режущее в правой руке: нож, штык, сапёрная лопата, топор.
 *
 * ФОРМУ ЗАДАЁТ КЛЕТОЧНАЯ КАРТА, МАТЕРИАЛ СЧИТАЕТСЯ ИЗ БОЕВЫХ ЧИСЕЛ. Приём тот
 * же, что у образцового `pistol.ts`, и принят он по той же причине: холст 128×128
 * ложится в кадр 320×200 пиксель в пиксель, клинок занимает в нём полсотни
 * пикселей, и на таком размере любой градиент — мыло, а шум — грязь. Прежняя
 * версия пакета рисовала наклонные плашки с цилиндрической затенкой и
 * попиксельным шумом; выходило гладкое серое пятно без граней.
 *
 * Разница с пистолетом одна, и она вынужденная: у клинка ТРИ такта удара, и
 * между ними он ходит через весь кадр под разными углами. Рукописной ASCII-карты
 * на каждый такт это стоило бы трёх листов по две с половиной тысячи символов, и
 * править их пришлось бы поштучно. Поэтому карта здесь СОБИРАЕТСЯ: геометрия
 * такта штампует в сетку 64×64 не цвета, а КОДЫ МАТЕРИАЛОВ, и дальше идут ровно
 * два прохода пистолета — тела клетками 2×2 и кромки по одному пикселю. Клетка
 * остаётся клеткой, тонов остаётся пять, свет остаётся сверху-слева. Кисть при
 * этом всё-таки рукописная: её форму никакая геометрия не выражает.
 *
 * Опознавательный знак класса — ОДНА СВЕТЛАЯ ГРАНЬ ВДОЛЬ РЕЖУЩЕЙ КРОМКИ. На
 * плоских тонах она читается лучше любой детали: тёмный обух с тыла, тело
 * полотна, светлая фаска по краю — три полосы, и вещь уже клинок, а не труба.
 *
 * Ракурс выбран вариатором, а не на глаз: шесть карт клинка и топора под углами
 * 75°..25° к вертикали были отрисованы одним листом. Пологий клинок (75°)
 * укладывается поперёк кадра и теряет длину — фаска вырождается в горизонтальную
 * черту; отвесный (25°) повторяет ошибку «вида в торец», от которой отказался
 * пистолет. Диагональ около 45° показывает и длину полотна, и фаску во всю её
 * длину, и при этом не достаёт до боковых столбцов холста.
 *
 * Безопасная зона холста: читаемое живёт в строках 22..100, строки ниже сотой
 * закрывает полоса HUD — туда идёт только масса предплечья и пятка рукояти.
 * В БОКОВЫЕ края упираться нельзя: они приходятся на треть ширины экрана.
 */

import { clamp, rgba } from '../../../core/pixutil';
import { registerViewmodel } from '../registry';
import { blend, contour, put } from '../draw';
import { VM } from '../types';

/** Клетка карты — два пикселя, ровно как у пистолета. */
const CELL = 2;
const GW = VM / CELL;
const GH = VM / CELL;

/**
 * Границы сетки — не вкус, а пороги холста, вбитые в саму запись клетки.
 *
 * Строка 10 — это пиксель 20: выше него силуэт лезет к прицелу. Столбцы 0 и 63 —
 * боковые края холста, они приходятся на треть ширины экрана, и дошедший до них
 * силуэт обрывается вертикальным срезом в воздухе. Наружу можно только вниз,
 * поэтому нижняя граница здесь одна — конец сетки.
 */
const TOP_ROW = 10;

/** Коды материалов. Символ называет МАТЕРИАЛ, а не цвет: оттенок решает `skin`. */
const enum M {
  EMPTY = 0,
  STEEL,   // полотно
  DARK,    // обух, тень железа
  EDGE,    // режущая фаска
  GRIP,    // рукоять
  GUARD,   // гарда
  GLOVE,   // резина перчатки
  KNUCK,   // сустав пальца
  GAP,     // щель между пальцами
  THUMB,   // большой палец
  CUFF,    // кожаный манжет
  SLEEVE,  // рукав
}

/** Поза одного такта. Угол считается ОТ ВЕРТИКАЛИ, влево — плюс. */
interface Pose {
  /** Кисть на рукояти, клетки. */
  hx: number; hy: number;
  /** Наклон клинка от вертикали, градусы. */
  deg: number;
  /** Габарит от кисти до острия, клетки. */
  len: number;
  /** Приближение к глазу: во столько раз крупнее железо и кисть. */
  z: number;
}

/**
 * Три такта ОДНОГО движения, а не три разные руки.
 *
 * Клинок ПРИБЛИЖАЕТСЯ к глазу и встаёт круче (занос), потом проносится поперёк
 * кадра вниз-влево (проводка) и возвращается. Похожие картинки означали бы, что
 * удара в кадре не видно вовсе.
 */
const POSES: Readonly<Record<string, Pose>> = {
  idle: { hx: 46, hy: 45, deg: 44, len: 46, z: 1.0 },
  swing: { hx: 50, hy: 48, deg: 27, len: 41, z: 1.14 },
  swing2: { hx: 48, hy: 42, deg: 74, len: 42, z: 1.04 },
};

/** Пять ступеней материала и ни одной между ними. */
function ramp(base: readonly [number, number, number]): readonly number[] {
  const at = (k: number) => rgba(clamp(base[0] * k), clamp(base[1] * k), clamp(base[2] * k));
  return [at(0.5), at(0.82), at(1.15), at(1.5), at(1.95)];
}

/**
 * Кисть в перчатке ликвидатора, сжатая на рукояти.
 *
 * Пальцы — ПОЛОСАМИ ПОПЕРЁК хвата: ряд сустава, ряд щели, снова ряд сустава.
 * Сплошное пятно резины читается куском, а не хватом, — то же правило, по
 * которому у пистолета чередуются `K` и `J`. Ось `y` карты идёт вдоль хвата, от
 * железа к локтю, и карта поворачивается вместе с ним.
 */
const FIST: readonly string[] = [
  '...NNNNNN...',
  '..NNNNNNNN..',
  '.NNNNNNNNNN.',
  '.NNNNNNNNNN.',
  '.JJJJJJJJJJ.',
  '.HHHHHHHHHT.',
  '.NNNNNNNNTT.',
  '.JJJJJJJJJT.',
  '.HHHHHHHHTT.',
  '.NNNNNNNNTT.',
  '.JJJJJJJJJT.',
  '..HHHHHHHT..',
  '..HHHHHHH...',
  '..CCCCCCC...',
  '..CCCCCCC...',
];

const FIST_CODES: Readonly<Record<string, M>> = {
  N: M.KNUCK, H: M.GLOVE, J: M.GAP, T: M.THUMB, C: M.CUFF,
};

/** Запись клетки. Пороги холста проверяются здесь, а не глазами по картинке. */
function set(g: Uint8Array, gx: number, gy: number, code: M): void {
  const x = Math.round(gx);
  const y = Math.round(gy);
  if (x < 1 || x > GW - 2 || y < TOP_ROW || y >= GH) return;
  g[y * GW + x] = code;
}

function at(g: Uint8Array, gx: number, gy: number): M {
  return (gx < 0 || gy < 0 || gx >= GW || gy >= GH) ? M.EMPTY : (g[gy * GW + gx] as M);
}

/** Наклонная плашка в клетках, с сужением от корня к концу. */
function slab(
  g: Uint8Array, x: number, y: number, ax: number, ay: number,
  len: number, h0: number, h1: number, code: M,
): void {
  const nx = -ay;
  const ny = ax;
  const steps = Math.max(1, Math.ceil(len * 2));
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const u = t * len;
    const h = h0 + (h1 - h0) * t;
    for (let s = -h; s <= h; s += 0.5) set(g, x + ax * u + nx * s, y + ay * u + ny * s, code);
  }
}

/**
 * Авторская карта, повёрнутая вдоль оси хвата.
 *
 * Обратным отображением, а не прямым: прямое рвёт карту в решето на любом угле,
 * кроме кратного 45°, и кисть рассыпается на отдельные клетки.
 */
function stampFist(g: Uint8Array, cx: number, cy: number, ax: number, ay: number, scale: number): void {
  const w = FIST[0].length;
  const h = FIST.length;
  const rad = Math.ceil((Math.max(w, h) * scale) / 2) + 2;
  const nx = -ay;
  const ny = ax;
  for (let y = Math.round(cy - rad); y <= cy + rad; y++) {
    for (let x = Math.round(cx - rad); x <= cx + rad; x++) {
      const dx = x - cx;
      const dy = y - cy;
      const ly = Math.round((dx * ax + dy * ay) / scale + h / 2);
      const lx = Math.round((dx * nx + dy * ny) / scale + w / 2);
      if (ly < 0 || ly >= h || lx < 0 || lx >= w) continue;
      const code = FIST_CODES[FIST[ly][lx]];
      if (code) set(g, x, y, code);
    }
  }
}

/**
 * Предплечье: конус ВНИЗ и за нижний срез — рука растёт из кадра, а не висит.
 *
 * Уходит вниз, а не в боковой угол: кулак ближнего боя сидит на строках 84..100,
 * и конус из него в угол пересёк бы правый край холста ВЫШЕ полосы HUD, где край
 * приходится на треть ширины экрана.
 */
function forearm(g: Uint8Array, wx: number, wy: number, tx: number, ty: number, r0: number): void {
  const d = Math.max(0.001, Math.hypot(tx - wx, ty - wy));
  const ax = (tx - wx) / d;
  const ay = (ty - wy) / d;
  slab(g, wx, wy, ax, ay, d, r0, r0 + 3, M.SLEEVE);
  // Светлая грань по верхне-левой стороне: ею рука и становится круглой.
  slab(g, wx - ay * (r0 - 1), wy + ax * (r0 - 1), ax, ay, d, 1, 1.5, M.GLOVE);
}

registerViewmodel({
  id: 'blade',
  slot: 'weapon',
  frames: ['idle', 'swing', 'swing2'],
  motion: { recoil: 1, bob: 1.1, swap: 0.18 },
  draw({ buf, frame, skin, rand }) {
    const [bD2, bD1, bM, , bH] = ramp(skin.body);
    const [gD2, , gM, gL] = ramp(skin.grip);
    const [, aD1, aM, aL] = ramp(skin.accent);
    /* Перчатка ликвидатора, а не голая кисть: голая рука — большое бледное пятно
     * тона бетона, и на пятидесяти пикселях она сливается со стеной при любой
     * анатомии. Тёмная резина держит силуэт, вспышку и кровь.
     *
     * Она ТЕМНЕЕ железа, и это ровно та же задача, что у пистолета, решённая в
     * другую сторону. Там корпус вороненый, и резину пришлось поднять, иначе
     * рука и ствол слипались в одно чёрное пятно. Здесь корпус — светлая сталь,
     * и та же резина слилась бы с ней в одно серое поле. Правило — КОНТРАСТ
     * рука/железо, а не число. */
    const gt = rand();
    const [vD2, vD1, vM, vL] = ramp([54 + gt * 12, 57 + gt * 12, 66 + gt * 14]);
    /** Холодный рефлекс: у резины блик голубовато-серый, а не телесный. */
    const RIM = rgba(122, 138, 160);
    const CUFF = rgba(96, 58, 30);
    const CUFF_LIT = rgba(134, 86, 46);

    /** Тело, светлая кромка, тёмная кромка — по одному на материал. */
    const MATERIAL: Readonly<Record<number, readonly [number, number, number]>> = {
      [M.STEEL]: [bM, bH, bD2],
      [M.DARK]: [bD2, bD1, bD2],
      [M.EDGE]: [bH, bH, bM],
      [M.GRIP]: [gM, gL, gD2],
      [M.GUARD]: [aM, aL, aD1],
      [M.GLOVE]: [vD1, vM, vD2],
      [M.KNUCK]: [vM, RIM, vD2],
      [M.GAP]: [vD2, vD1, vD2],
      [M.THUMB]: [vM, vL, vD2],
      [M.CUFF]: [CUFF, CUFF_LIT, rgba(48, 28, 14)],
      [M.SLEEVE]: [vD2, vD1, vD2],
    };

    const pose = POSES[frame] ?? POSES.idle;
    const z = pose.z;
    const rad = (pose.deg * Math.PI) / 180;
    const ax = -Math.sin(rad);
    const ay = -Math.cos(rad);
    const nx = -ay;
    const ny = ax;

    /* ── Габарит ──
     * Длина — это расстояние от кисти до острия позы, а не сумма кусков по
     * `skin`. Иначе тяжёлый клинок перерастает отведённое место и обрубается о
     * боковой край холста. Вылет клинков лежит в узкой полосе, и честнее не
     * растягивать его, а отдать всю разницу внутри класса толщине железа. */
    const span = pose.len * (0.9 + skin.barrel / 420);
    /* Тяжесть железа: у ножа клинок продолжает рукоять, у топора железо насажено
     * щекой на конец топорища. Это единственная настоящая разница внутри класса,
     * и она непрерывна — порога, за которым нож вдруг становится топором, нет. */
    const heavy = Math.max(0, Math.min(1, (skin.bulk - 8) / 3));

    const g = new Uint8Array(GW * GH);

    /* ── Рукоять и топорище ── */
    const haft = span * (0.16 + heavy * 0.42);
    const heelX = pose.hx + ax * haft;
    const heelY = pose.hy + ay * haft;
    slab(g, pose.hx - ax * 10 * z, pose.hy - ay * 10 * z, ax, ay, haft + 10 * z,
      (1.5 + skin.bulk * 0.07) * z, (1.4 + skin.bulk * 0.07) * z, M.GRIP);

    /* ── Полотно ──
     *
     * Железо выкладывается ОДНИМ ПРОХОДОМ ПОПЕРЁК: на каждом шаге вдоль оси
     * считаются обе границы силуэта, между ними ложится сталь, на тыльной
     * границе — обух, на внешней — фаска. Плашками это уже стояло и разъезжалось:
     * полотно сходило на остриё, а прямая полоса обуха оставалась на прежнем
     * отступе и висела рядом с клинком отдельной чёрточкой. Границу может
     * держать только тот, кто её и считает. */
    const edge = span - haft;
    const wBlade = (1.5 + skin.bulk * 0.16) * z;
    // Вылет щеки топора. У ножа `heavy` равен нулю, щека вырождается сама —
    // порога, за которым нож вдруг становится топором, здесь нет.
    const bit = heavy * (5 + skin.bulk * 0.22) * z;
    const steps = Math.max(1, Math.ceil(edge * 2));
    for (let i = 0; i <= steps; i++) {
      const t = i / steps;
      const u = t * edge;
      // Полотно ножа сходит на остриё; у топора оно держит толщину проушины,
      // иначе поверх щеки торчит второе, ножевое остриё, и вещь читается кайтом.
      const h = wBlade * (1 - t * (0.8 - heavy * 0.66));
      // Щека дугой: широка у лезвия, узка у проушины — клин, а не овал.
      const p = Math.max(0, (t - 0.12) / 0.88);
      const cheek = bit > 0.8 ? bit * Math.sin(p * Math.PI * 0.86) : 0;
      const bx = heelX + ax * u;
      const by = heelY + ay * u;
      for (let s = -h; s <= h + cheek; s += 0.5) set(g, bx + nx * s, by + ny * s, M.STEEL);
      // Обух — тёмная полоса с тыла; ею и читается толщина железа. Без неё сталь
      // остаётся плоской наклейкой при любом освещении.
      set(g, bx - nx * h, by - ny * h, M.DARK);
      /* Фаска ловит свет вдоль режущей кромки — ГЛАВНЫЙ опознавательный знак
       * класса, и на плоских тонах он читается лучше любой детали. Место у неё
       * одно на оба облика: у ножа это край полотна, у топора внешний край
       * щеки — ровно одна и та же граница силуэта. */
      if (t > 0.04) {
        set(g, bx + nx * (h + cheek), by + ny * (h + cheek), M.EDGE);
        set(g, bx + nx * (h + cheek - 0.7), by + ny * (h + cheek - 0.7), M.EDGE);
      }
    }

    /* ── Гарда ── */
    // Перекрестье стоит НАИСКОСЬ к клинку: строго поперечное читается плюсиком и
    // убивает разворот, ради которого весь силуэт и построен.
    const ga = 0.5;
    const qx = nx * Math.cos(ga) - ny * Math.sin(ga);
    const qy = nx * Math.sin(ga) + ny * Math.cos(ga);
    const guard = (2.2 + skin.bulk * 0.14) * z * (1 - heavy * 0.5);
    slab(g, pose.hx + ax * 3 - qx * guard, pose.hy + ay * 3 - qy * guard,
      qx, qy, guard * 2, 0.8 * z, 0.8 * z, M.GUARD);

    /* ── Рука ── */
    /* Предплечье входит из нижнего ПРАВОГО угла и уходит за него: рука растёт из
     * кадра, а не висит в нём. Толщина здесь не украшение — тонкий рукав под
     * полосой HUD не читается вовсе, и клинок повисает в воздухе сам по себе. */
    forearm(g, pose.hx - ax * 10 * z, pose.hy - ay * 10 * z, 56, GH + 10, 8 * z);
    stampFist(g, pose.hx, pose.hy, ax, ay, 1.24 * z);

    /* ── Сколы на железе ──
     * У дешёвого клинка их больше. Точками ПО ОБУХУ, а не по всему полотну:
     * крапление по телу читается изъеденной ржавчиной жестью, а щербины со
     * стороны спинки — сколами на железе. */
    const chips = Math.round(skin.wear * 5);
    for (let i = 0; i < chips; i++) {
      const u = edge * (0.2 + rand() * 0.6);
      const s = -wBlade * (0.4 + rand() * 0.5);
      const cx = Math.round(heelX + ax * u + nx * s);
      const cy = Math.round(heelY + ay * u + ny * s);
      if (at(g, cx, cy) === M.STEEL) set(g, cx, cy, M.DARK);
    }

    /* ── Тела ── */
    for (let gy = 0; gy < GH; gy++) {
      for (let gx = 0; gx < GW; gx++) {
        const mat = MATERIAL[at(g, gx, gy)];
        if (!mat) continue;
        const x = gx * CELL;
        const y = gy * CELL;
        for (let dy = 0; dy < CELL; dy++) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y + dy, mat[0]);
      }
    }

    /* ── Кромки ──
     * Клетка крупная, кромка тонкая: светлая грань сверху и слева, тёмная снизу
     * и справа. Это и есть «свет сверху-слева», и ровно этим плоская заливка
     * перестаёт быть наклейкой. */
    for (let gy = 0; gy < GH; gy++) {
      for (let gx = 0; gx < GW; gx++) {
        const ch = at(g, gx, gy);
        const mat = MATERIAL[ch];
        if (!mat) continue;
        const x = gx * CELL;
        const y = gy * CELL;
        if (at(g, gx, gy - 1) !== ch) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y, mat[1]);
        if (at(g, gx - 1, gy) !== ch) for (let dy = 0; dy < CELL; dy++) put(buf, x, y + dy, mat[1]);
        if (at(g, gx, gy + 1) !== ch) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y + CELL - 1, mat[2]);
        if (at(g, gx + 1, gy) !== ch) for (let dy = 0; dy < CELL; dy++) put(buf, x + CELL - 1, y + dy, mat[2]);
      }
    }

    contour(buf);

    /* ── Проводка ──
     * Смаз пройденной дуги за клинком: без него удар читается сменой позы, а не
     * движением. Кладётся ПОСЛЕ контура и только им: обведённый контуром, он
     * перестаёт быть смазом и становится вторым телом — залитым сектором в
     * чёрной рамке, который закрывает само оружие. */
    if (frame === 'swing2') {
      const trail = rgba(clamp(skin.body[0] * 1.2 + 46), clamp(skin.body[1] * 1.2 + 50), clamp(skin.body[2] * 1.2 + 56));
      const px = pose.hx * CELL;
      const py = pose.hy * CELL;
      /* Дуга идёт НАЗАД по ходу удара — туда, откуда клинок пришёл: от текущего
       * такта к предыдущему, а не вперёд. Вперёд она читается не смазом, а
       * вторым, полупрозрачным клинком.
       *
       * И она ЖЁСТКАЯ, в две ступени плотности с прореживанием через пиксель, а
       * не мягкая. Плавная заливка по альфе давала на этом размере серое облако
       * над клинком — то самое мыло, ради отказа от которого пакет и переписан. */
      const mid = span * CELL * 0.84;
      for (const [off, dens] of [[0, 0.62], [-4, 0.34], [4, 0.34]] as const) {
        const r = mid + off;
        const step = 0.9 / r;
        for (let a = 0.18; a <= 0.78; a += step) {
          const rx = ax * Math.cos(a) - ay * Math.sin(a);
          const ry = ax * Math.sin(a) + ay * Math.cos(a);
          const x = Math.round(px + rx * r);
          const y = Math.round(py + ry * r);
          if (((x + y) & 1) === 0) continue;
          /* Смаз подчиняется тем же порогам холста, что и сама карта: он идёт
           * ПОСЛЕ контура, минуя сетку, и без этой проверки уходил выше строки
           * прицела и за боковые столбцы — там, где силуэту нельзя, а следу от
           * него, стало быть, тоже. */
          if (y < TOP_ROW * CELL || x < CELL || x >= VM - CELL) continue;
          blend(buf, x, y, trail, dens * (1 - a / 0.78));
        }
      }
    }
  },
});
