/**
 * Пистолет: короткий ствол, магазин в рукояти, одна рука в перчатке.
 *
 * ОБРАЗЦОВЫЙ ПАКЕТ — по нему пишутся остальные силуэты.
 *
 * ФОРМУ ЗАДАЁТ АВТОРСКАЯ ПИКСЕЛЬНАЯ КАРТА, МАТЕРИАЛ СЧИТАЕТСЯ ИЗ БОЕВЫХ ЧИСЕЛ.
 * Это главное решение пакета, и оно принято после двух проваленных подходов.
 * Сперва ствол собирался из наклонных плашек с градиентной затенкой и шумом: на
 * холсте, который занимает в кадре полсотни пикселей, любой градиент — мыло, а
 * шум — грязь. Потом из многоугольников: силуэт стал управляемым, но пистолет —
 * это машина из десятка деталей, и подбор координат вслепую чинил одно, ломая
 * соседнее. Карта решает ровно эту беду: форма видна прямо в исходнике и
 * правится по пикселю, а цвет, износ, изолента и магазин по-прежнему выводятся
 * из `skin`, то есть из канонических характеристик вещи.
 *
 * Карта — это НЕ запечённая картинка. В ней нет ни одного цвета: символ
 * называет МАТЕРИАЛ, а какого он оттенка, насколько ржав и есть ли на рукояти
 * изолента, решают числа конкретного ствола. Один и тот же силуэт обслуживает
 * шесть пистолетов, и все шесть выглядят по-разному.
 *
 * Клетка карты — два пикселя, но КРОМКИ рисуются по одному: светлая фаска сверху
 * и слева, тёмная снизу и справа. Так держится правило «свет сверху-слева» из
 * рефов, и так крупная форма уживается с тонкой гранью, ради которой воронёный
 * металл вообще отличается от чёрной дыры в кадре.
 *
 * Безопасная зона холста: читаемое живёт в строках 22..100, строки 100..127
 * закрывает полоса HUD. В БОКОВЫЕ края упираться нельзя: они приходятся на
 * треть ширины экрана, и силуэт оборвался бы прямым срезом в воздухе.
 */

import { clamp, rgba } from '../../../core/pixutil';
import { registerViewmodel } from '../registry';
import { contour, line, put } from '../draw';
import { VM } from '../types';

/** Левый верхний угол карты на холсте. Клетка карты — два пикселя. */
const MAP_X = 26;
const MAP_Y = 34;
const CELL = 2;

/** Дульный срез. Из него светит вспышка, поэтому он объявлен, а не выведен. */
const MUZZLE_X = MAP_X + 2 * CELL;
const MUZZLE_Y = MAP_Y + 1 * CELL;

/**
 * Силуэт.
 *
 * `.` пусто · `S` затвор · `F` рамка · `B` канал ствола · `L` мушка · `R` курок
 * `G` рукоять · `T` изолента · `M` магазин
 * `H` перчатка · `K` сустав пальца · `J` щель между пальцами · `C` манжет
 * `A` рукав
 *
 * НАКЛОННЫЙ ХВАТ, А НЕ ВИД В ТОРЕЦ. Ствол уходит вверх-влево по диагонали, и
 * зритель видит БОКОВУЮ плоскость оружия: затвор, скобу, скос рукояти.
 *
 * Схема выбрана не на вкус, а по замеру. Сперва пистолет строился по домовской
 * схеме — ствол вертикально в точку прицела, — и одиннадцать заходов подряд
 * читался столбиком: батарейкой, флягой, гаечным ключом. Тогда шесть вариантов
 * карты (домовская, дюковская, широкий корпус, крупный план, револьвер,
 * самоделка) были отрисованы разом одним листом, и оружием читался ровно один —
 * дюковский. Причина простая: у Doom это спрайт с настоящей отрисовкой объёма,
 * а на плоских тонах вид в торец вырождается в столбик, потому что показывать
 * ему нечего. Профиль показывает форму, торец — нет.
 *
 * Кулаку домовский центр при этом идёт: кулак и есть масса анфас. Разные вещи
 * требуют разного ракурса, и это не противоречие, а разные задачи.
 */
const MAP: readonly string[] = [
  '..LL..............................',
  '.SBBSS............................',
  '.SBBSS............................',
  '.SSSSSS...........................',
  '..SSSSSSS.........................',
  '..SSSSSSSSS.......................',
  '...SSSSSSSSSS.....................',
  '...SSSSSSSSSSSS...................',
  '....SSSSSSSSSSSSS.................',
  '....SSSSSSSSSSSSSSS...............',
  '.....SSSSSSSSSSSSSSSR.............',
  '.....FFFFFFFFFFFFFFSR.............',
  '......FFFFFFFFFFFFFFF.............',
  '......FF.......FFGGGG.............',
  '......FF.......FGGGGG.............',
  '......FFFF....KKGGGGGK............',
  '.......KKKKKKKKKGGGGGK............',
  '.......JJJJJJJJJJJJJJJ............',
  '.......KKKKKKKKKGGGGGK............',
  '.......KKKKKKKKKTTTTTK............',
  '........JJJJJJJJJJJJJJ............',
  '........KKKKKKKKGGGGGK............',
  '........KKKKKKKKMMMMMK............',
  '.........JJJJJJJJJJJJ.............',
  '.........HHHHHHHMMMMM.............',
  '.........CCCCCCCCCCC..............',
  '..........CCCCCCCCCC..............',
  '..........AAAAAAAAA...............',
  '...........AAAAAAA................',
];

/** Пять ступеней материала и ни одной между ними. */
function ramp(base: readonly [number, number, number]): readonly number[] {
  const at = (k: number) => rgba(clamp(base[0] * k), clamp(base[1] * k), clamp(base[2] * k));
  return [at(0.5), at(0.82), at(1.15), at(1.5), at(1.95)];
}

registerViewmodel({
  id: 'pistol',
  slot: 'weapon',
  frames: ['idle', 'fire', 'reload'],
  muzzle: [MUZZLE_X, MUZZLE_Y],
  motion: { recoil: 1, flash: 0.055 },
  draw({ buf, frame, skin, rand }) {
    const [bD2, bD1, bM, bL, bH] = ramp(skin.body);
    const [gD2, , gM, gL] = ramp(skin.grip);
    const [, aD1, aM, aL] = ramp(skin.accent);
    /* Перчатка ликвидатора, а не голая кисть: на пятидесяти пикселях голая рука
     * — большое бледное пятно тона бетона, и она сливается со стеной при любой
     * анатомии. Тёмная резина держит силуэт, вспышку и кровь. */
    /* Резина СВЕТЛЕЕ воронёного железа, и это обязательное условие, а не вкус:
     * тёмная перчатка на тёмном стволе слилась в одно чёрное пятно, где не
     * читались ни пальцы, ни граница между рукой и оружием. Контраст рука/железо
     * здесь несёт всю композицию — ровно как светлая кисть у Doom против
     * чёрного ствола, только наоборот по знаку. */
    const gt = rand();
    const [vD2, vD1, vM, vL] = ramp([86 + gt * 16, 90 + gt * 16, 98 + gt * 18]);
    /** Холодный рефлекс: у резины блик голубовато-серый, а не телесный. */
    const RIM = rgba(122, 138, 160);
    const CUFF = rgba(96, 58, 30);
    const CUFF_LIT = rgba(134, 86, 46);
    /** Синяя изолента: фактура Хруща. Мотают её на то, что разваливается. */
    const TAPE = rgba(46, 74, 130);
    const BORE = rgba(12, 11, 13);

    /** Тело, светлая кромка, тёмная кромка — по одному на материал. */
    const MATERIAL: Readonly<Record<string, readonly [number, number, number]>> = {
      S: [bM, bH, bD2],
      F: [bD1, bL, bD2],
      B: [BORE, BORE, BORE],
      L: [bD1, bH, bD2],
      R: [bD1, bM, bD2],
      G: [gM, gL, gD2],
      T: [TAPE, rgba(78, 112, 176), rgba(24, 40, 78)],
      M: [aM, aL, aD1],
      H: [vM, vL, vD2],
      K: [vL, RIM, vD1],
      J: [vD2, vD1, vD2],
      C: [CUFF, CUFF_LIT, rgba(48, 28, 14)],
      A: [vD1, vM, vD2],
    };

    const reload = frame === 'reload';
    const ox = MAP_X + (reload ? 6 : 0);
    const oy = MAP_Y + (reload ? 14 : 0);
    /* Затвор на выстреле уходит НАЗАД по оси; ствол и дуло стоят на месте, иначе
     * вспышка оторвётся от объявленной точки. */
    const back = frame === 'fire' ? 2 : 0;

    const cellAt = (gx: number, gy: number): string => {
      if (gy < 0 || gy >= MAP.length) return '.';
      const row = MAP[gy];
      return gx < 0 || gx >= row.length ? '.' : row[gx];
    };
    /** Со сдвигом затвора: он ездит, всё остальное стоит. */
    const shifted = (gx: number, gy: number): string => {
      if (back) {
        const src = cellAt(gx, gy - back);
        if (src === 'S' || src === 'L') return src;
        const own = cellAt(gx, gy);
        return own === 'S' || own === 'L' ? '.' : own;
      }
      return cellAt(gx, gy);
    };

    /* ── Тела ── */
    for (let gy = 0; gy < MAP.length + back; gy++) {
      for (let gx = 0; gx < MAP[0].length; gx++) {
        const ch = shifted(gx, gy);
        if (ch === '.') continue;
        const mat = MATERIAL[ch];
        if (!mat) continue;
        const x = ox + gx * CELL;
        const y = oy + gy * CELL;
        for (let dy = 0; dy < CELL; dy++) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y + dy, mat[0]);
      }
    }

    /* ── Кромки ──
     * Клетка крупная, кромка тонкая: светлая грань сверху и слева, тёмная снизу
     * и справа. Это и есть «свет сверху-слева» из правил, и ровно этим плоская
     * заливка перестаёт быть наклейкой. */
    for (let gy = 0; gy < MAP.length + back; gy++) {
      for (let gx = 0; gx < MAP[0].length; gx++) {
        const ch = shifted(gx, gy);
        if (ch === '.' || ch === 'B') continue;
        const mat = MATERIAL[ch];
        if (!mat) continue;
        const x = ox + gx * CELL;
        const y = oy + gy * CELL;
        const open = (dx: number, dy: number) => {
          const n = shifted(gx + dx, gy + dy);
          return n === '.' || n !== ch;
        };
        if (open(0, -1)) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y, mat[1]);
        if (open(-1, 0)) for (let dy = 0; dy < CELL; dy++) put(buf, x, y + dy, mat[1]);
        if (open(0, 1)) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y + CELL - 1, mat[2]);
        if (open(1, 0)) for (let dy = 0; dy < CELL; dy++) put(buf, x + CELL - 1, y + dy, mat[2]);
      }
    }

    /* ── Что решают числа вещи ── */
    // Сколы на воронении: у дешёвого ствола их больше. Точками по кромке, а не
    // краплением по всему телу — крапление читается грязью, а не сколом.
    const chips = Math.round(skin.wear * 7);
    for (let i = 0; i < chips; i++) {
      const gy = 4 + Math.floor(rand() * 14);
      const gx = 7 + Math.floor(rand() * 3);
      if (shifted(gx, gy) !== 'S') continue;
      put(buf, ox + gx * CELL, oy + gy * CELL + 1, bL);
    }
    /* Насечка на заднем скате затвора: три штриха поперёк, в задней трети.
     * Красит ТОЛЬКО клетки самого затвора — иначе штрихи вылезают за силуэт и
     * висят в воздухе тремя чёрточками рядом с оружием. */
    for (let i = 0; i < 3; i++) {
      const gy = 6 + i * 2;
      for (let gx = 0; gx < MAP[0].length; gx++) {
        if (shifted(gx, gy + back) !== 'S') continue;
        for (let dx = 0; dx < CELL; dx++) put(buf, ox + gx * CELL + dx, oy + (gy + back) * CELL, bD2);
      }
    }
    // Окно выброса; на выстреле открыто и черно.
    if (frame === 'fire') {
      for (let gy = 12; gy < 15; gy++) {
        for (let dx = 0; dx < 4; dx++) put(buf, ox + 14 * CELL + dx, oy + gy * CELL + back * CELL, BORE);
      }
    }
    // Магазин на перезарядке вышел из рукояти и висит ниже.
    if (reload && skin.magazine > 0) {
      for (let gy = 34; gy < 38; gy++) {
        for (let gx = 9; gx < 13; gx++) {
          const x = ox + gx * CELL;
          const y = oy + gy * CELL;
          for (let dy = 0; dy < CELL; dy++) for (let dx = 0; dx < CELL; dx++) put(buf, x + dx, y + dy, aM);
        }
      }
    }

    /* ── Предплечье ── */
    /* Рука входит из нижнего правого угла и уходит ЗА него: рука растёт из
     * кадра, а не висит в нём. Полосами, а не конусом: конус даёт ровную заливку
     * без граней и читается доской. */
    const wristX = ox + 15 * CELL;
    const wristY = oy + 27 * CELL;
    const elbowX = VM - 4;
    const elbowY = VM + 34;
    line(buf, wristX, wristY, elbowX, elbowY, vD1, 15);
    line(buf, wristX - 5, wristY - 4, elbowX - 9, elbowY - 8, vM, 5);
    line(buf, wristX + 6, wristY + 5, elbowX + 6, elbowY + 6, vD2, 6);

    contour(buf);
  },
});
