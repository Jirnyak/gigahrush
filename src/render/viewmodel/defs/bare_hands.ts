/**
 * Пустая правая рука: кулак в три четверти.
 *
 * Нужна не для красоты: без неё безоружный боец смотрит в мир сквозь пустой
 * кадр, и удар кулаком ничем не отзывается. Кулак — такой же пакет, как ствол,
 * и на общих правах получает замах и откат.
 *
 * Держит те же четыре правила, что и образцовый `pistol.ts`:
 *
 * 1. ТРИ ЧЕТВЕРТИ, А НЕ АНФАС. Гребень костяшек идёт НАИСКОСЬ: указательная
 *    ближе к глазу и выше, мизинец дальше и ниже. Прошлая версия ставила
 *    костяшки линейкой поперёк кадра и читалась плоским коричневым пятном —
 *    точнее, ступнёй с пальцами, а не кулаком.
 * 2. СБОРКА ОТ ЗАПЯСТЬЯ. Запястье — якорь: от него растут и кисть, и
 *    предплечье. Сдвинув якорь, двигаешь весь кулак целиком, а не подгоняешь
 *    костяшки, большой палец и мясо поодиночке.
 * 3. ГАБАРИТ ЗАДАН, ОБЛИК ДЕЛИТ ЕГО. Длина кисти — это расстояние от запястья
 *    до гребня костяшек; фаланги и сжатие делят её, а не удлиняют.
 * 4. РУКА РАСТЁТ ИЗ УГЛА. Предплечье уходит в нижний правый угол и ЗА него.
 *
 * Геометрия холста (слот `weapon`): строка холста `r` ложится в строку экрана
 * `80 + r`, столбец 64 — центр экрана. Читаемое живёт в строках 22..100; строки
 * 100..127 закрывает полоса HUD, туда идёт только масса предплечья. В боковые
 * края упираться нельзя: они приходятся на треть ширины экрана, и силуэт
 * оборвался бы прямым срезом в воздухе. Наружу — только вниз.
 */

import { clamp, noise, rgba } from '../../../core/pixutil';
import { registerViewmodel } from '../registry';
import { contour, ellipse, line, skinTone } from '../draw';
import { VM } from '../types';

/** Запястье в покое. Якорь сборки: всё остальное считается от него. */
const WRIST_X = 84;
const WRIST_Y = 88;
/**
 * Локоть за нижним правым углом кадра. Левее самого угла нарочно: предплечье
 * обязано выйти ВНИЗ за край, а не срезаться о боковую границу холста.
 */
const ELBOW_X = VM * 0.8;
const ELBOW_Y = VM + 26;
/** Длина кисти: запястье → гребень костяшек. Габарит, который делит облик. */
const HAND_LEN = 26;

/** Тёмная щель между пальцами. Без неё они слипаются в одну колбасу. */
const GAP: readonly [number, number, number] = [62, 38, 32];

/**
 * Наклонная плашка со скруглёнными торцами и цилиндрической затенкой.
 *
 * Собственный примитив пакета, а не общий: у каждого силуэта своя геометрия, и
 * повтор между пакетами здесь замысел. На палец и предплечье ложится идеально —
 * именно затенка поперёк тела и делает валик круглым, а не наклейкой.
 */
function slab(
  buf: Uint32Array,
  x: number, y: number, ax: number, ay: number,
  len: number, half: number,
  base: readonly [number, number, number],
  seed: number, wear: number, round = 0,
): void {
  const nx = -ay;
  const ny = ax;
  const pad = Math.ceil(half + 2);
  const x0 = Math.max(0, Math.floor(Math.min(x, x + ax * len) - pad));
  const x1 = Math.min(VM - 1, Math.ceil(Math.max(x, x + ax * len) + pad));
  const y0 = Math.max(0, Math.floor(Math.min(y, y + ay * len) - pad));
  const y1 = Math.min(VM - 1, Math.ceil(Math.max(y, y + ay * len) + pad));
  for (let py = y0; py <= y1; py++) {
    for (let px = x0; px <= x1; px++) {
      const dx = px - x;
      const dy = py - y;
      const u = dx * ax + dy * ay;
      const v = dx * nx + dy * ny;
      if (u < -round || u > len + round) continue;
      let w = half;
      if (round > 0) {
        if (u < round) w = half * Math.sqrt(Math.max(0, 1 - ((round - u) / round) ** 2));
        else if (u > len - round) w = half * Math.sqrt(Math.max(0, 1 - ((u - (len - round)) / round) ** 2));
      }
      if (w <= 0 || Math.abs(v) > w) continue;
      /* Свет с одной стороны: блик ближе к левой кромке, тень к правой. Именно
       * это читается как «круглое»; ровная заливка читается наклейкой. */
      const t = v / half;
      const lit = 1.3 - (t + 0.46) * (t + 0.46) * 1.0;
      const n = (noise(px, py, seed) - 0.5) * (10 + wear * 40);
      const rust = wear > 0 && noise(px * 3, py * 3, seed + 7) < wear * 0.3;
      const r = rust ? base[0] * 0.6 + 60 : base[0];
      const g = rust ? base[1] * 0.48 + 28 : base[1];
      const b = rust ? base[2] * 0.42 + 15 : base[2];
      buf[py * VM + px] = rgba(clamp(r * lit + n), clamp(g * lit + n), clamp(b * lit + n));
    }
  }
}

registerViewmodel({
  id: 'bare_hands',
  slot: 'weapon',
  frames: ['idle', 'swing', 'swing2'],
  motion: { recoil: 0.8, bob: 1.15 },
  draw({ buf, frame, rand }) {
    const tone = skinTone(rand);
    const flesh = (k: number) => rgba(clamp(tone[0] * k), clamp(tone[1] * k), clamp(tone[2] * k));
    const mass = (k: number) => [tone[0] * k, tone[1] * k, tone[2] * k] as const;

    /* Такт удара. Меняется не только высота: кулак ПРИБЛИЖАЕТСЯ к глазу (`s`),
     * доворачивается запястьем (`t`) и дожимается (`curl`). Три кадра обязаны
     * читаться одним движением, а не тремя разными руками. */
    const pose = frame === 'swing'
      // Вынесен вперёд-вверх и крупнее: кулак у самого прицела.
      ? { x: 76, y: 72, t: -0.11, s: 1.55, curl: 1 }
      : frame === 'swing2'
        // Возврат: кулак ушёл вниз, довернулся и приотпущен.
        ? { x: 94, y: 98, t: -0.58, s: 1.2, curl: 0.4 }
        : { x: WRIST_X, y: WRIST_Y, t: -0.3, s: 1.28, curl: 0.85 };

    /* Ось кисти: от запястья К КОСТЯШКАМ, то есть вверх-влево. Названа по
     * смыслу — со знаком здесь легко построить всю кисть в обратную сторону и
     * выгнать её за нижний край, где от руки останется одно пятно мяса. */
    const hx = Math.sin(pose.t);
    const hy = -Math.cos(pose.t);
    /** Поперёк кисти: по этой оси лежит гребень костяшек, `+` к мизинцу. */
    const px = -hy;
    const py = hx;
    const u = (v: number) => v * pose.s;
    /** Точка кисти: `a` вдоль оси от запястья, `b` поперёк к мизинцу. */
    const at = (a: number, b: number) => [
      pose.x + (hx * a + px * b) * pose.s,
      pose.y + (hy * a + py * b) * pose.s,
    ] as const;

    /* ── Предплечье ── */
    // Конус в нижний правый угол и ЗА него: рука растёт из кадра, а не висит.
    const steps = 30;
    for (let i = 0; i <= steps; i++) {
      const t = i / steps;
      const r = u(16) + t * 9;
      ellipse(buf, pose.x + (ELBOW_X - pose.x) * t, pose.y + (ELBOW_Y - pose.y) * t, r, r,
        flesh(0.88 - t * 0.16));
    }
    // Свет один на всю руку — сверху слева, поэтому у предплечья светлая
    // локтевая грань и тёмная дальняя. Ровный конус читается трубой из мяса.
    for (let i = 0; i <= steps; i++) {
      const t = i / steps;
      ellipse(buf, pose.x + u(13) + (ELBOW_X + 14 - pose.x) * t, pose.y + u(6) + (ELBOW_Y - pose.y) * t,
        u(7) + t * 4, u(6) + t * 4, flesh(0.68 - t * 0.1));
      ellipse(buf, pose.x - u(9) + (ELBOW_X - 24 - pose.x) * t, pose.y + u(16) + (ELBOW_Y - 12 - pose.y) * t,
        u(5) - t * 1.4, u(4.4) - t * 1.2, flesh(1.06));
    }

    /* ── Гребень костяшек ── */
    /* Он и отличает кулак от варежки. Идёт НАИСКОСЬ: указательная костяшка
     * ближе к глазу — она выше и крупнее, мизинец уходит вглубь и вниз. Ровный
     * ряд одинаковых бугров поперёк кадра читается ступнёй, а не рукой. */
    const knuck: Array<readonly [number, number, number]> = [];
    for (let k = 0; k < 4; k++) {
      const t = (k + 0.5) / 4;
      // Дуга гребня плюс перспективный завал к мизинцу.
      knuck.push([HAND_LEN + Math.sin(t * Math.PI) * 3 - k * 2.6, -15 + k * 10.2, 6.3 - k * 0.5]);
    }

    /* ── Тыльная сторона кисти ── */
    /* Три широкие плашки внахлёст, а не одна и не по валику на пясть.
     *
     * Одна плашка уводит дальнюю треть кисти в чёрное: затенка у неё
     * квадратичная и на полуширине в пятнадцать пикселей доходит до нуля.
     * Четыре пястных валика впритык дают четыре борозды во всю длину кисти, и
     * кулак читается растопыренной пятернёй — обе крайности уже проверены.
     * Каждая следующая плашка закрывает тёмную кромку предыдущей, и на тыльной
     * стороне остаются мягкие рёбра пясти и одна честная теневая грань со
     * стороны мизинца. */
    const DORSUM: readonly (readonly [number, number, number, number])[] = [
      // сдвиг поперёк, полуширина, длина, яркость
      [-9, 14, 36, 1.02],
      [3, 12, 32, 0.99],
      [12, 7, 27, 0.9],
      [17, 4.5, 22, 0.7],
    ];
    for (let k = 0; k < DORSUM.length; k++) {
      const [b0, half, len, k0] = DORSUM[k];
      const [dx, dy] = at(-13, b0);
      slab(buf, dx, dy, hx, hy, u(len), u(half), mass(k0), 11 + k, 0.05, u(half * 0.7));
    }

    // Сухожилия от костяшек к запястью: видны тем сильнее, чем дожат кулак.
    const tendon = flesh(1.08 + pose.curl * 0.16);
    for (let k = 0; k < 3; k++) {
      const b = -10 + k * 10;
      const [t1x, t1y] = at(HAND_LEN - 7, b);
      const [t2x, t2y] = at(-3, b * 0.45);
      line(buf, t1x, t1y, t2x, t2y, tendon, 1);
    }

    /* ── Пальцы ── */
    /* В КУЛАКЕ пальцы сложены ОТ глаза, поэтому над гребнем видны только шапки
     * головок пясти: верх кисти обязан читаться зубчатой дугой из четырёх
     * бугров, а не четырьмя торчащими вверх колбасами. Прошлая версия
     * выпускала фаланги во всю длину и давала растопыренную ладонь «стоп».
     * Длину фаланги раздаёт `curl`: на откате кулак приотпущен, и пальцы
     * вылезают — это и есть разница между кадрами, а не одна высота. */
    const fingerDir: Array<readonly [number, number]> = [];
    for (let k = 0; k < 4; k++) {
      const fan = -0.17 + k * 0.12;
      fingerDir.push([hx * Math.cos(fan) - hy * Math.sin(fan), hx * Math.sin(fan) + hy * Math.cos(fan)]);
    }

    /* Сам гребень: полоса мяса ВДОЛЬ ряда костяшек, ровной заливкой. Без неё
     * между буграми зияют вырезы до самой пясти. Плашкой её класть нельзя —
     * затенка у плашки идёт поперёк оси и поперёк гребня кладёт чёрный брус. */
    const [r0x, r0y] = at(knuck[0][0] + 1, knuck[0][1] - 5);
    const [r3x, r3y] = at(knuck[3][0] - 1, knuck[3][1] + 5);
    for (let i = 0; i <= 24; i++) {
      const t = i / 24;
      ellipse(buf, r0x + (r3x - r0x) * t, r0y + (r3y - r0y) * t, u(5.2), u(4.8), flesh(0.88 - t * 0.08));
    }

    const fingerLen = (k: number) => u((1 - pose.curl) * (15 - k * 0.8));
    for (let k = 0; k < 4; k++) {
      const [a, b, r] = knuck[k];
      const [fx, fy] = fingerDir[k];
      const [kx, ky] = at(a, b);
      const R = u(r * 1.16);
      // Фаланга. На дожатом кулаке её нет вовсе: она ушла от глаза за костяшку.
      const ext = fingerLen(k);
      if (ext > 1) {
        slab(buf, kx, ky, fx, fy, ext, R * 0.84, mass(1.06 - k * 0.05), 59 + k, 0, R * 0.72);
        const jx = kx + fx * ext;
        const jy = ky + fy * ext;
        // Второй сустав уходит от глаза: не бугор, а тень под складкой.
        ellipse(buf, jx - fx * R * 0.5, jy - fy * R * 0.5, R * 0.5, R * 0.46, flesh(0.72));
      }
      // Тень под костяшкой: она и отделяет бугор от пясти. Прямая складка во
      // всю ширину кисти читалась брусом, поперёк руки положенным.
      ellipse(buf, kx - hx * u(r * 0.9), ky - hy * u(r * 0.9), R * 0.92, R * 0.86, flesh(0.6));
      /* Головка пясти шаром: тремя вложенными пятнами со сдвигом к свету.
       * Ровный круг одного тона читается заклёпкой, а не костью под кожей. */
      ellipse(buf, kx, ky, R, R * 0.95, flesh(0.92));
      ellipse(buf, kx - px * u(1.2) - hx * u(1.2), ky - py * u(1.2) - hy * u(1.2), R * 0.74, R * 0.7, flesh(1.14));
      ellipse(buf, kx - px * u(2.4) - hx * u(2.2), ky - py * u(2.4) - hy * u(2.2), R * 0.34, R * 0.31, flesh(1.44));
    }
    // Щели между бугров. Отдельным проходом и ПОВЕРХ: бугры перекрываются, и
    // щель, положенная под них, тут же зарастает соседней костяшкой.
    for (let k = 0; k < 3; k++) {
      const [a0, b0] = knuck[k];
      const [a1, b1] = knuck[k + 1];
      const [gx, gy] = at((a0 + a1) * 0.5, (b0 + b1) * 0.5);
      const [fx, fy] = fingerDir[k];
      slab(buf, gx - fx * u(5), gy - fy * u(5), fx, fy,
        u(7) + fingerLen(k) * 0.8, u(1.05), GAP, 53 + k, 0, u(1));
    }

    /* ── Большой палец ── */
    // Лежит ПОПЕРЁК согнутых пальцев и ближе всех к глазу, поэтому рисуется
    // последним. Без него кулак читается культёй.
    const [tbx, tby] = at(-2, -24);
    const tdx = px * 0.95 + hx * 0.31;
    const tdy = py * 0.95 + hy * 0.31;
    const tn = Math.hypot(tdx, tdy);
    const tax = tdx / tn;
    const tay = tdy / tn;
    // Валик большого. Своя затенка кладёт тень с нижней стороны — она и
    // отрывает его от согнутых пальцев, отдельная тёмная плашка тут лишняя.
    slab(buf, tbx, tby, tax, tay, u(23), u(5.2), mass(1.16), 73, 0, u(4.8));
    // Вторая плашка внахлёст со стороны тени — тем же приёмом, что и пясть:
    // одиночный валик такой ширины проваливает нижнюю треть большого в чёрное.
    slab(buf, tbx - tay * u(4.4), tby + tax * u(4.4), tax, tay, u(21), u(4.4), mass(0.88), 75, 0, u(4));
    // Мякоть у основания и сустав на середине: без них большой — просто труба.
    ellipse(buf, tbx + u(1), tby - u(1), u(5), u(4.6), flesh(1.16));
    ellipse(buf, tbx + tax * u(12), tby + tay * u(12), u(3.2), u(2.9), flesh(1.32));

    contour(buf);
  },
});
