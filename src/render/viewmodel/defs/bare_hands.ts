/**
 * Пустая правая рука: кулак в три четверти.
 *
 * Нужна не для красоты: без неё безоружный боец смотрит в мир сквозь пустой
 * кадр, и удар кулаком ничем не отзывается. Кулак — такой же пакет, как ствол,
 * и на общих правах получает замах и откат.
 *
 * РИСУЕТСЯ ПЛОСКИМИ БЛОКАМИ ПО РАМПЕ ИЗ ПЯТИ ТОНОВ, а не объёмной заливкой.
 * Это главное правило пакета, и оно записано здесь, потому что нарушалось.
 * Прежняя версия строила кулак из наклонных плашек с квадратичной затенкой и
 * попиксельным шумом — то есть рендерила гладкий объём. На холсте 128×128,
 * который ложится в кадр 320×200 пиксель в пиксель, кулак занимает полсотни
 * пикселей: любой градиент на таком размере превращается в мыло, а шум — в
 * грязь. Форму на этом размере несут СИЛУЭТ, ЖЁСТКИЙ КОНТУР И РЕЗКИЕ ГРАНИЦЫ
 * ТОНОВ, и ничего больше. Деталь здесь приносится в жертву форме сознательно.
 *
 * Отсюда четыре правила:
 *
 * 1. ПЯТЬ ТОНОВ И НИ ОДНОГО ПРОМЕЖУТОЧНОГО. Тень, полутень, основной, свет,
 *    блик. Плавных переходов нет, шума нет: граница тонов — это ребро формы.
 * 2. ГРЯДА КОСТЯШЕК В ПЕРСПЕКТИВЕ. Указательная ближе к глазу: выше и почти
 *    вдвое крупнее мизинца. Ровный ряд одинаковых бугров — это подъём ступни с
 *    пальцами, а не кулак; тыл кисти и подъём ступни одна и та же форма, и
 *    различает их только перспектива гряды да глубина щелей.
 * 3. ЗАПЯСТЬЕ УЖЕ КУЛАКА. Без перехвата кисть переходит в предплечье одной
 *    сплошной плахой мяса, и рука перестаёт читаться рукой.
 * 4. РУКА РАСТЁТ ИЗ УГЛА. Предплечье уходит в нижний правый угол и ЗА него.
 *
 * Геометрия холста (слот `weapon`): строка холста `r` ложится в строку экрана
 * `80 + r`, столбец `c` — в столбец `192 + c`, то есть холст прижат к правому
 * краю кадра. Читаемое живёт в строках 22..100; строки 100..127 закрывает полоса
 * HUD, туда идёт только масса предплечья. В ЛЕВЫЙ край упираться нельзя: он
 * приходится на середину кадра, и силуэт оборвался бы прямым срезом в воздухе.
 * Наружу — вправо и вниз.
 */

import { clamp, rgba } from '../../../core/pixutil';
import { registerViewmodel } from '../registry';
import { contour, line, put } from '../draw';
import { VM } from '../types';

/** Центр кулака в покое. Якорь сборки: всё остальное считается от него. */
const FIST_X = 74;
const FIST_Y = 74;
/**
 * Локоть за нижним правым углом кадра. Левее самого угла нарочно: предплечье
 * обязано выйти ВНИЗ за край, а не срезаться о боковую границу холста.
 */
const ELBOW_X = VM - 2;
const ELBOW_Y = VM + 40;

/**
 * Блок со срезанными углами — единственная форма, из которой собран кулак.
 *
 * Срез вместо скругления по окружности: на этом размере скругление съедает по
 * пикселю то с одной стороны, то с другой и грызёт кромку, а прямой срез
 * читается как фаска и держит силуэт.
 */
function block(
  buf: Uint32Array,
  x0: number, y0: number, x1: number, y1: number,
  cut: number, color: number,
): void {
  const ay0 = Math.round(y0);
  const ay1 = Math.round(y1);
  for (let y = ay0; y <= ay1; y++) {
    const inset = Math.max(0, cut - Math.min(y - ay0, ay1 - y));
    for (let x = Math.round(x0 + inset); x <= Math.round(x1 - inset); x++) put(buf, x, y, color);
  }
}

/**
 * Многоугольник плоской заливкой по строкам.
 *
 * Силуэт кулака задаётся ИМ, а не набором прямоугольников. Прямоугольники здесь
 * уже стояли: кисть выходила кирпичом с приклеенными сверху шариками, потому
 * что осевой блок не умеет ни сузиться к запястью, ни завалить верхнюю кромку
 * по гряде костяшек. Форму на этом размере несёт контур, и задавать его надо
 * прямо.
 */
function poly(buf: Uint32Array, pts: readonly (readonly [number, number])[], color: number): void {
  let y0 = Infinity;
  let y1 = -Infinity;
  for (const p of pts) { if (p[1] < y0) y0 = p[1]; if (p[1] > y1) y1 = p[1]; }
  const xs: number[] = [];
  for (let y = Math.round(y0); y <= Math.round(y1); y++) {
    xs.length = 0;
    const scan = y + 0.5;
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i];
      const b = pts[(i + 1) % pts.length];
      if ((a[1] > scan) === (b[1] > scan)) continue;
      xs.push(a[0] + ((scan - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
    }
    xs.sort((p, q) => p - q);
    for (let i = 0; i + 1 < xs.length; i += 2) {
      for (let x = Math.round(xs[i]); x <= Math.round(xs[i + 1]); x++) put(buf, x, y, color);
    }
  }
}

/** Диск плоской заливкой. Костяшка — это диск, а не эллипс с градиентом. */
function disc(buf: Uint32Array, cx: number, cy: number, r: number, color: number): void {
  const y0 = Math.floor(cy - r);
  const y1 = Math.ceil(cy + r);
  for (let y = y0; y <= y1; y++) {
    const dy = (y - cy) / r;
    if (dy * dy > 1) continue;
    const half = r * Math.sqrt(1 - dy * dy);
    for (let x = Math.round(cx - half); x <= Math.round(cx + half); x++) put(buf, x, y, color);
  }
}

registerViewmodel({
  id: 'bare_hands',
  slot: 'weapon',
  frames: ['idle', 'swing', 'swing2'],
  motion: { recoil: 0.8, bob: 1.15 },
  draw({ buf, frame, rand }) {
    /* Рука в ПЕРЧАТКЕ ликвидатора, а не голая.
     *
     * Это не украшение: голая кисть — это большое бледное пятно ровно того же
     * тона, что бетон вокруг, и на пятидесяти пикселях она сливается со стеной
     * при любой анатомии. Тёмная вулканизированная резина даёт контраст силуэту
     * и, что важнее, держит дульную вспышку и кровь — на светлой коже они не
     * читаются вовсе. Заодно перчатка ставит бойца в мир: это спецовка
     * ликвидатора, а не голые руки прохожего. */
    const t = rand();
    const tone = [40 + t * 13, 42 + t * 13, 49 + t * 15] as const;
    /* Рампа. Пять ступеней и ни одной между ними — на этом размере
     * промежуточный тон не читается объёмом, он читается грязью. */
    const step = (k: number) => rgba(clamp(tone[0] * k), clamp(tone[1] * k), clamp(tone[2] * k));
    const SH2 = step(0.5);
    const SH1 = step(0.76);
    const MID = step(1.05);
    const LIT = step(1.5);
    const HI = step(2.0);
    /* Холодный рефлекс по дуге костяшек: у резины и кожи блик не телесный, а
     * голубовато-серый, и на тёмном теле он — единственное, чем форма читается. */
    const RIM = rgba(118, 132, 154);
    /** Кожаный манжет: он и отделяет кисть от рукава одной тёплой полосой. */
    const CUFF = rgba(96, 58, 30);
    const CUFF_LIT = rgba(132, 84, 44);

    /* Такт удара. Кулак ПРИБЛИЖАЕТСЯ к глазу и поднимается, на возврате уходит
     * вниз и приотпускается. Высота такта считается от гребня, а не от центра:
     * гряда стоит выше центра на треть кулака, и замах легко выносит её за
     * строку прицела, которая холсту оружия не принадлежит. */
    const pose = frame === 'swing'
      ? { x: 68, y: 66, s: 1.16, open: 0 }
      : frame === 'swing2'
        ? { x: 86, y: 88, s: 0.94, open: 1 }
        : { x: FIST_X, y: FIST_Y, s: 1, open: 0 };

    /** Точка кулака: локальные пиксели от центра, с масштабом такта. */
    const X = (v: number) => pose.x + v * pose.s;
    const Y = (v: number) => pose.y + v * pose.s;
    /* ── Предплечье ── */
    /* Полосой, а не конусом из полусотни эллипсов: конус давал ровную заливку
     * без граней и читался доской из мяса. Полос три — тело, светлая верхняя
     * грань, тёмная нижняя, — и рука становится круглой ровно этими двумя
     * границами тона. */
    const armX = X(12);
    const armY = Y(22);
    line(buf, armX, armY, ELBOW_X, ELBOW_Y, MID, Math.round(26 * pose.s));
    line(buf, armX - 8 * pose.s, armY - 8 * pose.s, ELBOW_X - 12, ELBOW_Y - 12, LIT, Math.round(8 * pose.s));
    line(buf, armX + 10 * pose.s, armY + 10 * pose.s, ELBOW_X + 8, ELBOW_Y + 8, SH1, Math.round(10 * pose.s));

    /** Многоугольник в локальных пикселях такта. */
    const P = (pts: readonly (readonly [number, number])[], color: number) =>
      poly(buf, pts.map((p) => [X(p[0]), Y(p[1])] as const), color);

    /* ── Запястье ── */
    /* Перехват: заметно уже кулака и темнее его. Камера здесь широкоугольная и
     * стоит вплотную, поэтому кисть обязана быть крупнее запястья не чуть-чуть,
     * а в полтора раза — это и есть перспективное сокращение, без которого рука
     * читается ровной трубой одинаковой толщины во всю длину. */
    P([[5, 13], [23, 19], [27, 34], [7, 30]], SH1);
    P([[7, 13], [20, 18], [22, 29], [9, 26]], MID);

    /* ── Тыльная сторона ── */
    /* Одно тело с завалом: широкое у гряды костяшек, сужается к запястью, и
     * верхняя кромка идёт вниз-вправо вслед за грядой. Осевой блок этого не
     * умеет — от него кисть выходила кирпичом. */
    const BODY: readonly (readonly [number, number])[] = [
      [-34, -6], [-25, -17], [4, -14], [24, -4], [31, 8], [22, 26], [-14, 28], [-33, 14],
    ];
    P(BODY, MID);
    // Свет сверху слева, тень со стороны мизинца и снизу: три грани, три
    // границы тона. Между ними ничего — на этом размере полутон читается грязью.
    /* Светлая грань — УЗКАЯ полоса по верхне-левой кромке, а не половина кисти.
     * Широкой она была ровно того же тона, что большой палец, и палец в ней
     * растворялся: оставалась одна тёмная обводка вокруг пустого светлого поля. */
    P([[-34, -6], [-25, -17], [2, -14], [4, -6], [-20, -8], [-32, 2]], LIT);
    P([[-32, -5], [-26, -14], [-15, -12], [-19, -6], [-31, 1]], HI);
    P([[20, -6], [31, 8], [22, 26], [8, 24], [14, 4]], SH1);
    P([[-12, 21], [20, 20], [22, 26], [-14, 28]], SH1);

    /* Кожаный манжет перчатки. Единственное тёплое пятно на всей руке, и стоит
     * оно ровно на стыке кисти и рукава — том самом месте, где рука иначе
     * читается одной трубой без сустава. Кладётся ПОСЛЕ тела кисти: до него
     * тело закрывало манжет и от него оставалась одна коричневая щепка. */
    P([[2, 18], [27, 25], [26, 34], [1, 27]], CUFF);
    P([[2, 18], [27, 25], [27, 28], [2, 21]], CUFF_LIT);
    P([[1, 31], [26, 38], [26, 34], [1, 27]], SH2);

    /* ── Гряда костяшек ── */
    /* Дуга, а не лесенка: СРЕДНЯЯ костяшка выше всех, мизинец ниже всех. Так
     * стоит кулак у человека, и именно этим гряда отличается от ряда пальцев
     * ступни. Здесь уже стояла лесенка с указательной наверху — она честно
     * передавала перспективу, но не анатомию, и кулак оставался подъёмом стопы.
     *
     * Шаг между костяшками к мизинцу сокращается (перспектива), радиус тоже —
     * но крупнее прочих именно СРЕДНЯЯ, а не ближняя к глазу. */
    const KN = 4;
    const KX = [-26, -11, 2, 12] as const;
    const KY = [-15, -18, -13, -4] as const;
    const KR = [9.6, 10.2, 8.4, 6.2] as const;
    const kx = (k: number) => KX[k];
    const ky = (k: number) => KY[k];
    const kr = (k: number) => KR[k];

    // Общая тень под грядой: она отделяет костяшки от пясти одной границей и
    // идёт вниз-вправо вместе с ней, а не поперёк кадра.
    P([[-31, -5], [-4, -1], [22, 8], [20, 13], [-6, 4], [-31, 0]], SH1);

    /* ── Сложенные фаланги ── */
    /* Под грядой видны средние фаланги согнутых пальцев — так стоит кулак у
     * Duke и Shadow Warrior, и именно они не дают тылу кисти читаться пустой
     * плахой мяса. Здесь была голая пясть, и её нижний левый угол вместе с
     * большим пальцем складывался в клюв.
     *
     * Рисуются ДО костяшек: головка пясти ближе к глазу и обязана лечь поверх
     * своей фаланги, а не наоборот. */
    for (let k = 0; k < KN; k++) {
      const x0 = X(KX[k] - KR[k] * 0.86);
      const x1 = X(KX[k] + KR[k] * 0.86);
      const yt = Y(KY[k] + KR[k] * 0.3);
      const yb = Y(KY[k] + KR[k] * 0.3 + 16 - k * 1.4);
      const cut = Math.round(3 * pose.s);
      block(buf, x0, yt, x1, yb, cut, k <= 1 ? LIT : MID);
      // Тень в основании фаланги и щель до соседней: без них фаланги слипаются.
      block(buf, x0, yb - 5 * pose.s, x1, yb, cut, SH1);
      block(buf, x1 - pose.s, yt + 2 * pose.s, x1, yb, 0, SH2);
    }

    for (let k = 0; k < KN; k++) {
      const cx = X(kx(k));
      const cy = Y(ky(k));
      const r = kr(k) * pose.s;
      // Дальние костяшки темнее ближних: без этого гряда снова выравнивается в
      // ряд одинаковых бугров, сколько её ни ужимай в размере.
      const away = k * 0.5;
      disc(buf, cx, cy + r * 0.55, r, SH2);
      /* Рефлекс серпом: диск холодного тона сдвинут вверх-влево и вылезает
       * из-под тела костяшки на один-два пикселя. На тёмной резине это
       * единственное, чем гряда вообще читается формой. */
      disc(buf, cx - r * 0.1, cy - r * 0.12, r, RIM);
      disc(buf, cx, cy, r * 0.96, k >= 3 ? MID : LIT);
      disc(buf, cx - r * 0.28, cy - r * 0.3, r * 0.5, k >= 3 ? LIT : HI);
      if (away > 1.4) disc(buf, cx + r * 0.5, cy + r * 0.3, r * 0.4, MID);

      /* На возврате кулак приотпущен, и над костяшкой выглядывает первая
       * фаланга. Это и есть разница между тактами — не одна высота. */
      if (pose.open > 0) {
        block(buf, cx - r * 0.72, cy - r * 2.1, cx + r * 0.72, cy - r * 0.6, Math.round(r * 0.4), MID);
        block(buf, cx - r * 0.72, cy - r * 2.1, cx - r * 0.1, cy - r * 0.9, Math.round(r * 0.3), LIT);
      }
    }
    // Ложбины между головками пясти: короткие, вниз от гребня. Во всю длину
    // кисти они читаются прорезями в мясе, вверх поверх костяшек — следом когтей.
    for (let k = 0; k < KN - 1; k++) {
      const gx = X((kx(k) + kx(k + 1)) * 0.5);
      const gy = Y((ky(k) + ky(k + 1)) * 0.5);
      block(buf, gx - 1.5 * pose.s, gy - 2 * pose.s, gx + 1.5 * pose.s, gy + 4 * pose.s, 1, SH2);
    }

    /* ── Большой палец ── */
    /* ГЛАВНЫЙ опознавательный знак сжатого кулака, и потому рисуется последним.
     * Он не лежит вдоль низа кисти — он ЗАМКНУТ ПОВЕРХ указательного и среднего
     * пальцев, идёт снизу-слева вверх-вправо и сужается к ногтю. Пока он лежал
     * низом поперёк кисти, он читался повязкой, а кулак — вообще не кулаком. */
    /* Держится ВНУТРИ силуэта кисти: наружу он торчал клювом и превращал кулак
     * в птичью голову. Обхват — это палец, ЛЕЖАЩИЙ на пальцах, а не отдельная
     * деталь, приставленная сбоку. */
    P([[-31, 10], [0, 3], [3, 11], [-31, 22]], SH2);
    P([[-31, 8], [0, 1], [3, 9], [-31, 20]], LIT);
    // Верхняя грань пальца и БЛИК НА СУСТАВЕ: свет сверху-слева, и сустав
    // большого — одна из четырёх точек, которые его ловят.
    P([[-31, 8], [0, 1], [1, 4], [-31, 11]], HI);
    disc(buf, X(-14), Y(7), 3.4 * pose.s, HI);
    // Ноготь: метка на самом кончике, иначе палец кончается ничем.
    P([[-1, 2], [3, 5], [2, 9], [-2, 7]], MID);

    contour(buf);
  },
});
