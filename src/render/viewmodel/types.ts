/**
 * Вьюмодель: то, что боец держит в руках, глазами самого бойца.
 *
 * Слоя два и они те же, что у актора: правая рука рисует `entity.weapon`,
 * левая — `entity.tool`. Никакой отдельной «модели игрока» здесь нет и быть не
 * может: одержимость меняет ссылку на текущее тело, и руки обязаны смениться
 * вместе с ним. Поэтому всё считается ОТ АКТОРА, а не от глобала игрока.
 *
 * Холст квадратный, 128×128, ровно как у спрайтов сущностей и запечённого арта,
 * и рисуется он 1:1 в кадр 320×200 — это домовский масштаб без единой лишней
 * константы. Из этого же следует, что вьюмодель живёт ВНУТРИ низкого кадра:
 * её красит свет этажа, мнёт самосбор и размывает блум.
 */

import { S } from '../../core/pixutil';

/** Сторона холста вьюмодели. Кратна спрайтовой, чтобы масштаб был целым. */
export const VM = S * 2;

/** Рука. Имена совпадают с полями `Entity`, чтобы не заводить второй словарь. */
export type ViewmodelSlot = 'weapon' | 'tool';

/**
 * Кадр позы. Больше не нужно: покачивание, отдача, увод и наклон — это
 * ПРЕОБРАЗОВАНИЯ квада, а не отдельные картинки. Рисуются только те состояния,
 * которые нельзя выразить сдвигом: выстрел, замах и второй такт замаха.
 */
export type ViewmodelFrameKey = 'idle' | 'fire' | 'swing' | 'swing2' | 'reload';

/** Кадр, который обязан уметь каждый пакет. Остальные необязательны. */
export const VIEWMODEL_BASE_FRAME: ViewmodelFrameKey = 'idle';

/**
 * Визуальные параметры конкретного ствола поверх архетипа.
 *
 * Архетип решает силуэт (пистолет, дробовик, клинок), а это — чем один
 * пистолет отличается от другого. Значения нормированы в 0..1 либо в пикселях
 * холста, чтобы пакет не знал про мировые единицы.
 */
export interface ViewmodelSkin {
  /** Основной металл/корпус. */
  body: readonly [number, number, number];
  /** Вторичный материал: дерево, пластик, кожа рукояти. */
  grip: readonly [number, number, number];
  /** Акцент: калёная сталь, медь, свечение энергетики. */
  accent: readonly [number, number, number];
  /** Длина ствола/лезвия в пикселях холста. */
  barrel: number;
  /** Толщина корпуса в пикселях холста. */
  bulk: number;
  /** Магазин/барабан/бак есть и насколько велик, 0 — нет вовсе. */
  magazine: number;
  /** Приклад/вторая рука на цевье. */
  stock: boolean;
  /** Износ: 0 — новое, 1 — ржавое самоделье. */
  wear: number;
  /** Свечение акцента, 0 — мёртвый металл, 1 — энергетика. */
  glow: number;
}

/** Контекст одной отрисовки пакета в буфер 128×128. */
export interface ViewmodelDrawContext {
  /** Буфер `VM*VM`, уже залитый `CLEAR`. Пакет пишет прямо в него. */
  buf: Uint32Array;
  /** Какой кадр просят. Пакет обязан отработать хотя бы `idle`. */
  frame: ViewmodelFrameKey;
  /** Параметры конкретного ствола. */
  skin: ViewmodelSkin;
  /**
   * Детерминированный источник случайности, засеянный ИДЕНТИФИКАТОРОМ ствола.
   * Один и тот же ствол выглядит одинаково между запусками и в тестах.
   * Недетерминированный источник здесь запрещён так же, как и везде.
   */
  rand: () => number;
}

/** Настройка моторики, если архетипу мало общей. */
export interface ViewmodelMotion {
  /** Множитель отдачи. 1 — пистолетный кик. */
  recoil: number;
  /** Множитель амплитуды покачивания. */
  bob: number;
  /** Секунд на доставание/убирание. */
  swap: number;
  /** Секунд свечения дульной вспышки. */
  flash: number;
}

/**
 * Пакет одной вещи в руке.
 *
 * Пакеты равнозначны и не сливаются: перекрасить один ствол нельзя, задев
 * соседний. Повтор между ними — замысел, а не долг.
 */
export interface ViewmodelDef {
  /** Идентификатор пакета: архетип (`pistol`) либо конкретный ствол (`gauss`). */
  id: string;
  /** В какой руке эта вещь может оказаться. */
  slot: ViewmodelSlot;
  /** Какие кадры пакет умеет рисовать. `idle` обязателен. */
  frames: readonly ViewmodelFrameKey[];
  /** Точка дульной вспышки в координатах холста. Нет — вспышки не будет. */
  muzzle?: readonly [number, number];
  /** Отклонения моторики от общей. */
  motion?: Partial<ViewmodelMotion>;
  /** Собственно рисование. */
  draw(ctx: ViewmodelDrawContext): void;
}

/**
 * Один квад к отрисовке. Координаты — пиксели кадра 320×200, отсчёт от левого
 * верхнего угла холста вьюмодели.
 */
export interface ViewmodelQuad {
  /**
   * Ключ кэша текстуры. Проход по нему только кэширует и ничего не ищет: что
   * именно рисуется, решено до него, в `runtime`.
   */
  key: string;
  /** Готовый холст `VM*VM`. */
  sprite: Uint32Array;
  x: number;
  y: number;
  /** Масштаб холста. 1 — пиксель в пиксель. */
  scale: number;
  /** Наклон вокруг центра низа холста, радианы. */
  roll: number;
  /** Множитель цвета: свет этажа, фонарь, самосбор. */
  tint: readonly [number, number, number];
  alpha: number;
  /** Аддитивное смешивание — для вспышки и энергетики. */
  additive: boolean;
}

/** Готовый кадр вьюмодели: от нуля до трёх квадов, порядок = порядок отрисовки. */
export interface ViewmodelFrameState {
  quads: readonly ViewmodelQuad[];
}

/** Пустой кадр: руки не рисуются вовсе. */
export const EMPTY_VIEWMODEL_FRAME: ViewmodelFrameState = { quads: [] };
